// Type-level tests: checked by `tsc` (npm run typecheck), never run. The types come from
// the OpenAPI of the core sample (test/fixtures, regenerated by `npm run fixture`).

import { can, createClient, Filter, nextPage, pagination } from '../src/index.js';
import type { PermitMeta, RouteSetPath } from '../src/index.js';
import type { paths } from './fixtures/schema.js';

const api = createClient<paths>({ baseUrl: 'https://api.test' });
const PARENT = '/api/v1/entity/parent_entity/';
// keeps the checked values used
export const seen: unknown[] = [];
const CHILD = '/api/v1/entity/child_entity/';

export const routeSets: RouteSetPath<paths>[] = [PARENT, CHILD];
// @ts-expect-error an item path is not a route set
export const notRouteSet: RouteSetPath<paths> = '/api/v1/entity/parent_entity/{item_id}/';

export async function listTyped(): Promise<void> {
  const page = await api.list(PARENT, {
    filter: Filter.and(Filter.where('is_active', true), Filter.where('price__gte', 10)),
    search: 'apple',
    sort: ['-dt_created'],
    page: { limit: 20, offset: 0 },
    fields: { 'entity.parent_entity': ['name', 'price'] },
    meta: ['pagination'],
  });
  const first = page.data[0];
  if (first) {
    const name: string = first.attributes.name;
    // @ts-expect-error an unknown attribute
    seen.push(first.attributes.no_such_field);
    // @ts-expect-error the name is a string
    const wrong: number = first.attributes.name;
    seen.push(name, wrong);
  }
  seen.push(nextPage(page));
  seen.push(pagination(page));

  // @ts-expect-error an unknown path
  await api.list('/api/v1/entity/no_such_entity/');
  // @ts-expect-error a list is called on the path of the route set, not of an item
  await api.list('/api/v1/entity/parent_entity/{item_id}/');
  // @ts-expect-error list does not accept include
  await api.list(PARENT, { include: ['child_entities'] });
  // @ts-expect-error a list has sparse fieldsets only for its own type
  await api.list(PARENT, { fields: { 'entity.child_entity': ['child_name'] } });
  // @ts-expect-error an unknown meta field
  await api.list(PARENT, { meta: ['no_such_meta'] });
  // @ts-expect-error the filter is built with Filter, not written as a string
  await api.list(PARENT, { filter: 'name=apple' });
}

export async function itemTyped(id: string): Promise<void> {
  const item = await api.retrieve(PARENT, id, {
    include: ['child_entities'],
    fields: { 'entity.parent_entity': ['name'], 'entity.child_entity': ['child_name'] },
  });
  const name: string = item.data.attributes.name;
  seen.push(name);

  const created = await api.create(
    PARENT,
    { data: { type: 'entity.parent_entity', attributes: { name: 'apple' }, relationships: {} } },
    { include: ['child_entities'] },
  );
  seen.push(created.data.id);

  await api.create(PARENT, {
    // @ts-expect-error a required attribute is missing
    data: { type: 'entity.parent_entity', attributes: { price: 10 }, relationships: {} },
  });
  await api.create(PARENT, {
    data: {
      type: 'entity.parent_entity',
      // @ts-expect-error an unknown attribute
      attributes: { name: 'apple', no_such_field: 1 },
      relationships: {},
    },
  });
  await api.create(PARENT, {
    data: {
      type: 'entity.parent_entity',
      // @ts-expect-error a value outside the enum
      attributes: { name: 'apple', state: 'no_such_state' },
      relationships: {},
    },
  });

  await api.update(PARENT, id, {
    data: { id, type: 'entity.parent_entity', attributes: { is_active: false }, relationships: {} },
  });
  await api.destroy(PARENT, id);
  // @ts-expect-error retrieve needs an id
  await api.retrieve(PARENT);
}

export async function endpointsTyped(id: string): Promise<void> {
  await api.relationship(PARENT, id, 'child_entities', 'add', [
    { type: 'entity.child_entity', id: 'c1' },
  ]);
  await api.relationship(PARENT, id, 'extended_entity', 'replace', null);
  // @ts-expect-error an unknown relationship operation
  await api.relationship(PARENT, id, 'child_entities', 'set', null);

  const listSchema: Record<string, unknown> = await api.schema(PARENT, 'list');
  const updateSchema: Record<string, unknown> = await api.schema(PARENT, 'update', id);
  // @ts-expect-error the schema of an update is of an item
  await api.schema(PARENT, 'update');
  // @ts-expect-error the route sets of the sample are not statusy
  await api.schema(PARENT, 'transit', id);
  seen.push(listSchema, updateSchema);

  const filterFields = await api.filterFields(CHILD);
  seen.push(filterFields.fields);

  // @ts-expect-error the route sets of the sample are not statusy
  await api.transit(PARENT, id, 'to_done');
}

export async function permitTyped(id: string): Promise<void> {
  const page = await api.list(PARENT, { meta: ['pagination'] });
  // @ts-expect-error the meta of a route set without bazis-permit has no permission fields
  seen.push(can(page.meta, 'change', id));
  seen.push(can({ crud_actions: ['view', 'change'] }, 'view'));
  // @ts-expect-error not an access action
  seen.push(can({ crud_actions: [] }, 'edit'));
  // @ts-expect-error a list meta checks an item by its id only for change and delete
  seen.push(can({ for_change: [] }, 'view', id));
}

// The custom actions of a route set (`@http_post('/count/')`), as openapi-typescript renders
// them: the core sample has none.
type ActionPaths = paths & {
  '/api/v1/entity/parent_entity/count/': {
    post: {
      requestBody: { content: { 'application/json': { priority?: 'low' | 'high' | null } } };
      responses: { 200: { content: { 'application/json': { task: string } } } };
    };
  };
  '/api/v1/entity/parent_entity/{item_id}/summary/': {
    get: { responses: { 200: { content: { 'application/json': { total: number } } } } };
  };
  // `@http_get('/check/')` with the arguments `code: str` and `limit: int | None = None`:
  // query parameters of its operation
  '/api/v1/entity/parent_entity/check/': {
    get: {
      parameters: { query: { code: string; limit?: number | null }; header?: never; path?: never; cookie?: never };
      responses: { 200: { content: { 'application/json': { valid: boolean } } } };
    };
  };
  // the download route of bazis-uploadable and bazis-bg
  '/api/v1/entity/parent_entity/{item_id}/download/': {
    get: { responses: { 200: { content: { 'application/octet-stream': unknown } } } };
  };
};

export async function actionTyped(id: string): Promise<void> {
  const actions = createClient<ActionPaths>();
  const started = await actions.action(PARENT, 'count', { priority: 'high' });
  const task: string = started.task;
  // @ts-expect-error the response has no such field
  seen.push(started.id);
  // @ts-expect-error a body of another shape
  await actions.action(PARENT, 'count', { priority: 'urgent' });
  // @ts-expect-error the route set has no such action
  await actions.action(PARENT, 'export', {});
  // @ts-expect-error an action of an item is called with its id
  await actions.action(PARENT, 'summary');
  // @ts-expect-error the action is a POST
  await actions.action(PARENT, 'count', undefined, { method: 'get' });
  const summary = await actions.itemAction(PARENT, id, 'summary', undefined, { method: 'get' });
  const total: number = summary.total;
  // @ts-expect-error the action of an item is a GET
  await actions.itemAction(PARENT, id, 'summary');
  // @ts-expect-error schema_list is not an action of an item
  await actions.itemAction(PARENT, id, 'schema_list', undefined, { method: 'get' });
  const checked = await actions.action(PARENT, 'check', undefined, { method: 'get', query: { code: 'A1', limit: 2 } });
  const valid: boolean = checked.valid;
  // @ts-expect-error a parameter of another type
  await actions.action(PARENT, 'check', undefined, { method: 'get', query: { code: 1 } });
  // @ts-expect-error a parameter the action does not declare
  await actions.action(PARENT, 'check', undefined, { method: 'get', query: { code: 'A1', page: 2 } });
  // @ts-expect-error a required parameter is missing
  await actions.action(PARENT, 'check', undefined, { method: 'get', query: { limit: 2 } });
  // @ts-expect-error the action has no query parameters
  await actions.itemAction(PARENT, id, 'summary', undefined, { method: 'get', query: { code: 'A1' } });
  const file = await actions.download(PARENT, id);
  const name: string | null = file.name;
  // @ts-expect-error a route set without a download route
  await createClient<paths>().download(PARENT, id);
  seen.push(task, total, name ?? '', valid);
}

export function customActions(meta: PermitMeta): boolean {
  // @ts-expect-error a custom action is named as the method of the route set, `action_<name>`
  can(meta, 'export');
  return can(meta, 'action_export');
}
