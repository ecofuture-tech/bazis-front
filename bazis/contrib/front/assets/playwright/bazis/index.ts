// The helpers of the end-to-end tests: the steps of the scenarios of the specs over the
// screens, through their `data-bz` marks only. The tests generated by
// `manage.py bazis_front e2e` (`e2e/generated/`) call them with `PRODUCT` of
// `e2e/generated/product.ts` (the test users and the routes of the specs), and so can the
// tests of the product (`e2e/custom/`). They wait with the auto-waiting of Playwright and on
// the marks of the states, never for a fixed time but for the confirmation of a deletion,
// which a hand-written screen may not have (`CONFIRMATION_WAIT`). The tests run again on a
// database that keeps what the previous runs created: a test finds the items it created by
// their ids (`created`), and the notifications that came since it started.

import path from 'node:path';

import { errors, expect, type Locator, type Page, type Response } from '@playwright/test';

import { CAPABILITIES } from '@/bazis/generated/contract';

/**
 * The part of the specs that the helpers read, `PRODUCT` of `e2e/generated/product.ts`: the
 * test user of each role of spec/product.yaml (`test_user`, null without one; `anonymous`:
 * the users who do not log in) and the route of each screen of spec/screens/.
 */
export interface Product {
  readonly roles: Readonly<Record<string, { readonly username: string | null; readonly anonymous?: boolean }>>;
  readonly screens: Readonly<Record<string, { readonly route: string }>>;
}

/** A role of the specs. */
export type Role<P extends Product> = keyof P['roles'] & string;

/** A screen of the specs. */
export type ScreenId<P extends Product> = keyof P['screens'] & string;

/** The values of fields by name, scalars as in the specs. */
export type Values = Readonly<Record<string, string | number | boolean | null>>;

/**
 * The values of the fields of a form by name: a scalar, or the labels of the related items
 * of a to-many relationship (a list, `[]` for none).
 */
export type FormValues = Readonly<Record<string, string | number | boolean | null | readonly string[]>>;

/** The states that the screens render (`state:<state>`). */
export type State = 'loading' | 'empty' | 'loaded' | 'error' | 'forbidden' | 'not_found' | 'invalid';

/** The selector of the mark `data-bz="<kind>:<id>"`. */
export function bz(kind: string, id: string): string {
  return `[data-bz=${JSON.stringify(`${kind}:${id}`)}]`;
}

/** The marks of a failure: the error states and the errors of the fields. */
const FAILURES = [
  ...['error', 'forbidden', 'not_found', 'invalid'].map((state) => bz('state', state)),
  '[data-bz^="error:"]',
];
const FAILED = FAILURES.join(', ');

/** The attribute that the helpers set on the marks of a failure shown before a step. */
const SEEN = 'data-bz-seen';

/** The marks of a failure shown since the step started. */
const NEW_FAILED = FAILURES.map((it) => `${it}:not([${SEEN}])`).join(', ');

/** The login screen of the template (`LoginForm`), where the router sends a user without a session. */
export const LOGIN_ROUTE = '/login';

/** The files that `upload` takes, `e2e/fixtures/` of the frontend. */
const FIXTURES = path.join(import.meta.dirname, '..', 'fixtures');

/**
 * The pattern of the paths of a route of the specs: `/tasks/:id` is any `/tasks/<id>`, with or
 * without a trailing slash.
 */
export function routePattern(route: string): RegExp {
  const parts = route
    .replace(/\/+$/, '')
    .split('/')
    .map((part) => (part.startsWith(':') ? '[^/]+' : part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')));
  return new RegExp(`^${parts.join('/')}/?$`);
}

/** A text that is the whole text of an element. */
function exactly(value: string | number | boolean | null): RegExp {
  const text = value === null ? '' : String(value);
  return new RegExp(`^\\s*${text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*$`);
}

/** A day of `expectDay`: `YYYY-MM-DD` as it is, `today`, `today+<n>` or `today-<n>` from the day of the run, in UTC. */
function dayOfRun(day: string): string {
  const relative = /^today(?:([+-])(\d+))?$/.exec(day);
  if (relative === null) return day;
  const [, sign, days = '0'] = relative;
  const date = new Date();
  date.setUTCDate(date.getUTCDate() + (sign === '-' ? -1 : 1) * Number(days));
  return date.toISOString().slice(0, 10);
}

/**
 * A value of `fill` for an input of a date or a date-time: `today`, `today+<n>` or
 * `today-<n>` as in `expectDay`, followed by ` HH:MM` for a date-time (`today 10:30`); any
 * other value as it is (`2030-03-04`, `2030-03-04T10:00`).
 */
function dateOfRun(value: string): string {
  const relative = /^(today(?:[+-]\d+)?)(?: (\d{2}:\d{2}))?$/.exec(value);
  if (relative === null) return value;
  const [, day = 'today', time] = relative;
  return time === undefined ? dayOfRun(day) : `${dayOfRun(day)}T${time}`;
}

/** The languages that `language` goes through before it gives up. */
const MAX_LANGUAGES = 20;

/** How long `confirm` waits for the dialog of a confirmation before it assumes there is none, ms. */
const CONFIRMATION_WAIT = 2_000;

/** The button of the dialog that confirms a transit that the specs confirm (`confirm` of the workflow). */
const CONFIRM_TRANSIT = '[role="dialog"] [data-bz^="action:confirm-"]';

/**
 * The application in a page, at a screen of the specs. The steps act on the current screen
 * (set by `open` and `expectScreen`) and on the open form, the `<form>` with
 * `action:submit` (a dialog, the edit of a card, a form screen).
 */
export class App<P extends Product = Product> {
  private current: ScreenId<P> | null = null;

  /** The ids of the items that the submits of this test created (`submit`). */
  private readonly created = new Set<string>();

  /** When this test started: `expectNotification` takes the notifications since. */
  private readonly started = Date.now();

  constructor(
    readonly page: Page,
    readonly product: P,
  ) {}

  /** The current screen, `screen:<id>`. */
  screen(): Locator {
    if (this.current === null) throw new Error('No screen is open: start with `open` or `expectScreen`.');
    return this.page.locator(bz('screen', this.current));
  }

  /** The open form. */
  form(): Locator {
    return this.page.locator(`form:has(${bz('action', 'submit')})`);
  }

  /** Opens a screen by its route (one without the id of an item) and waits for its state. */
  async open(screen: ScreenId<P>): Promise<void> {
    const target = this.product.screens[screen];
    if (target === undefined) throw new Error(`The screen ${screen} is not in the specs.`);
    const { route } = target;
    if (route.includes(':')) {
      throw new Error(`The screen ${screen} shows an item (${route}): reach it with openItem.`);
    }
    await this.page.goto(route);
    await this.expectScreen(screen);
  }

  /**
   * Opens the first item of the current screen whose cells `cell:<name>` have exactly these
   * texts: a row of its list (`list:<entity>`; without one, an item `row:<id>` of the screen,
   * of a board or a calendar), or of its last items `recent:<in>` (a dashboard): on the page
   * shown, else searched with the search of the list (`field:$search`), each text of `where`
   * in turn, else on the next pages (`action:next-page`) of the list without a search, or with
   * more items of the columns of a board (`action:more`); fails when no page has it. A list
   * that grows with every run (the items that the scenarios create) is searched, never read on
   * its first page only. With `created`, only an item that this test created (`submit`): never
   * one of a previous run with the same texts.
   */
  async openItem({ where, in: recent, created = false }: { where: Values; in?: string; created?: boolean }): Promise<void> {
    await (await this.row(where, { recent, created })).click();
  }

  /**
   * Selects the row of the list of the current screen that `openItem` would open, its
   * checkbox `select:<id>`, for a bulk action; the rows selected before stay selected.
   */
  async select({ where, created = false }: { where: Values; created?: boolean }): Promise<void> {
    await (await this.row(where, { created })).locator('[data-bz^="select:"]').check();
  }

  /**
   * Runs a bulk action of the list of the current screen on the selected rows, `bulk:<id>`,
   * confirmed in its dialog (`action:confirm-bulk`), and waits until it is done (the action
   * is no longer offered: the selection is cleared) or shows an error (`error:bulk`).
   */
  async bulk(id: string): Promise<void> {
    const button = this.screen().locator(bz('bulk', id));
    await this.seen(this.page.locator('body'));
    await button.click();
    await this.page.locator(bz('action', 'confirm-bulk')).click();
    await this.until(button, this.page.locator(NEW_FAILED), `the bulk action ${id} is done or shows an error`);
  }

  /**
   * Moves the item of the board of the current screen that `openItem` would open to the
   * column of a status, by its menu (`action:move`, then `move:<status>`), confirmed in its
   * dialog when the specs confirm the transit, and waits until it is in the column
   * `column:<status>`; fails as soon as the move is refused (`error:move`, or another error
   * shown), with the error.
   */
  async move({ where, to, created = false }: { where: Values; to: string; created?: boolean }): Promise<void> {
    const row = await this.row(where, { created });
    const mark = (await row.getAttribute('data-bz')) ?? '';
    await this.seen(this.page.locator('body'));
    await row.locator(bz('action', 'move')).click();
    await this.page.locator(bz('move', to)).click();
    const moved = this.screen().locator(`${bz('column', to)} [data-bz=${JSON.stringify(mark)}]`);
    const failed = this.page.locator(NEW_FAILED);
    await this.confirmTransit(async () => (await moved.count()) > 0 || (await failed.count()) > 0);
    await expect
      .poll(async () => (await moved.count()) > 0 || (await failed.count()) > 0, { message: `the item is moved to ${to} or shows an error` })
      .toBe(true);
    if ((await moved.count()) === 0) {
      // the first: the mark of the refusal holds the state of its error
      const shown = (await failed.first().innerText()).replace(/\s+/g, ' ').trim();
      throw new Error(`The item ${mark} was not moved to ${to}: ${shown || 'an error is shown'}.`);
    }
  }

  /** Runs an action of the current screen, `action:<id>` (in the tab of a card that has it). */
  async action(id: string): Promise<void> {
    const button = this.screen().locator(bz('action', id));
    await this.reveal(button);
    await button.click();
  }

  /**
   * Confirms the action `<id>` of the current screen in its dialog, `action:confirm-<id>`
   * (the deletion of the item of a card), and waits until the dialog is closed; the dialog
   * must be shown, but with `optional` (a hand-written screen may run the action without a
   * confirmation), where nothing is done when none is shown within 2 s.
   */
  async confirm(id: string, { optional = false }: { optional?: boolean } = {}): Promise<void> {
    const button = this.page.locator(bz('action', `confirm-${id}`));
    if (optional) {
      const shown = await button.waitFor({ timeout: CONFIRMATION_WAIT }).then(
        () => true,
        (error: unknown) => {
          if (error instanceof errors.TimeoutError) return false;
          throw error;
        },
      );
      if (!shown) return;
    }
    await button.click();
    await expect(button).toBeHidden();
  }

  /**
   * Fills fields of the open form, `field:<name>`: a text, a number, a date; a select (a
   * choice) by the label of its option, the native one of the browser or that of Radix (a
   * combobox whose popup is its listbox), null by its option that clears the value
   * (`data-value=""` in that of Radix); a combobox (the picker of a relationship) by the
   * label of the item, searched in its popup, null by its option that clears the value; the
   * picker of a to-many relationship by the list of the labels of its items, which replace
   * those it had (`[]`: none); a checkbox, or a checkbox or a switch of Radix (`role`), by
   * true or false; an input of a date or a date-time also by a day of the run (`today`,
   * `today+1 10:30`: `dateOfRun`).
   */
  async fill(values: FormValues): Promise<void> {
    const form = this.form();
    for (const [name, value] of Object.entries(values)) {
      const control = form.locator(bz('field', name));
      await this.reveal(control);
      const kind = await control.evaluate((element) => {
        const role = element.getAttribute('role');
        if (role === 'combobox') return 'combobox';
        if (role === 'checkbox' || role === 'switch') return 'checkbox';
        return element instanceof HTMLInputElement ? element.type : element.tagName.toLowerCase();
      });
      if (typeof value === 'object' && value !== null) {
        if (kind !== 'combobox') throw new Error(`The field ${name} is not the picker of a to-many relationship.`);
        await this.chooseAll(name, control, value);
      } else if (kind === 'checkbox') await control.setChecked(value === true);
      else if (kind === 'select') await control.selectOption(value === null ? { value: '' } : { label: String(value) });
      else if (kind === 'combobox') await this.choose(control, value);
      else if (kind === 'date' || kind === 'datetime-local') await control.fill(value === null ? '' : dateOfRun(String(value)));
      else await control.fill(value === null ? '' : String(value));
    }
  }

  /**
   * Chooses an item in a combobox: opens its popup (`aria-controls`), finds the option of the
   * label (`option`; in a select of Radix, whose popup is the listbox of its options, the
   * option itself) and clicks it, or the option that clears the value (`data-value=""`);
   * waits until the popup is closed.
   */
  private async choose(control: Locator, value: string | number | boolean | null): Promise<void> {
    const popup = await this.openPopup(control);
    if (value === null) await popup.locator('[role="option"][data-value=""]').click();
    else if ((await popup.getAttribute('role')) === 'listbox') await popup.getByRole('option', { name: exactly(value) }).click();
    else await (await this.option(popup, value)).click();
    await expect(popup).toHaveCount(0);
  }

  /**
   * Sets the items of the picker of a to-many relationship: opens its popup (a listbox with
   * `aria-multiselectable`, which stays open), clears it with the option `data-value=""`,
   * selects the option of each label (`option`) and closes the popup with Escape.
   */
  private async chooseAll(name: string, control: Locator, labels: readonly string[]): Promise<void> {
    const popup = await this.openPopup(control);
    const listbox = popup.locator('[role="listbox"]');
    await expect(listbox).toHaveCount(1);
    if ((await listbox.getAttribute('aria-multiselectable')) !== 'true') {
      throw new Error(`The field ${name} is the picker of a to-one relationship: fill it with one label.`);
    }
    const clear = popup.locator('[role="option"][data-value=""]');
    await clear.click();
    await expect(clear).toHaveAttribute('aria-selected', 'true');
    for (const label of labels) {
      const option = await this.option(popup, label);
      await option.click();
      await expect(option).toHaveAttribute('aria-selected', 'true');
    }
    await this.page.keyboard.press('Escape');
    await expect(popup).toHaveCount(0);
  }

  /** Opens the popup of a combobox (`aria-controls`, which a select of Radix has only while it is open). */
  private async openPopup(control: Locator): Promise<Locator> {
    await control.click();
    await expect(control).toHaveAttribute('aria-controls', /./);
    return this.page.locator(`[id=${JSON.stringify((await control.getAttribute('aria-controls')) ?? '')}]`);
  }

  /**
   * The option of a label in the popup of a combobox, listed: searched in the search of the
   * popup, or, in a popup without one (its route set has no search fields), the next page
   * read (the option without `data-value`) until the item is listed, each page waited for on
   * its own.
   */
  private async option(popup: Locator, value: string | number | boolean): Promise<Locator> {
    const option = popup.getByRole('option', { name: exactly(value) });
    // the search and the list are rendered together (an empty list may be hidden)
    await expect(popup.locator('[role="listbox"]')).toHaveCount(1);
    if (await popup.getByRole('combobox').count()) {
      await popup.getByRole('combobox').fill(String(value));
      return option;
    }
    const options = popup.getByRole('option');
    const more = popup.locator('[role="option"]:not([data-value])');
    // the item, or the next page: the option of the next page is gone while it loads
    await expect(option.or(more).first()).toBeVisible();
    while (!(await option.count())) {
      const listed = await options.count();
      await more.click();
      await expect.poll(() => options.count()).not.toBe(listed);
      await expect(option.or(more).first()).toBeVisible();
    }
    return option;
  }

  /**
   * Uploads a file (a path in `e2e/fixtures/`) into a file field of the open form, its input
   * `field:<name>`, and waits until it is uploaded (the field `upload:<name>` is no longer
   * busy, its `aria-busy` absent or `"false"`, and shows the name of the file) or shows an
   * error of this upload.
   */
  async upload(field: string, file: string): Promise<void> {
    const form = this.form();
    await this.seen(form);
    await form.locator(bz('field', field)).setInputFiles(path.join(FIXTURES, file));
    const zone = form.locator(bz('upload', field));
    const name = path.basename(file);
    await expect
      .poll(
        async () =>
          (await form.locator(NEW_FAILED).count()) > 0 ||
          ((await zone.getAttribute('aria-busy')) !== 'true' && (await zone.innerText()).includes(name)),
        { message: `the file ${name} is uploaded into ${field} or shows an error` },
      )
      .toBe(true);
  }

  /**
   * Submits the open form and waits until it is closed (saved) or shows an error of this
   * submit (not one of a previous submit), which the next step expects (`expectError`,
   * `expectState`). With `saved`, a submit that must save: it fails with the errors shown
   * when the form stays open. The items that it creates are those of this test (`created` of
   * `openItem`): the answers 201 of the creates of the backend, their item in `data.id`.
   */
  async submit({ saved = false }: { saved?: boolean } = {}): Promise<void> {
    const form = this.form();
    await this.seen(form);
    await this.recordCreated(async () => {
      await form.locator(bz('action', 'submit')).click();
      await this.until(form, form.locator(NEW_FAILED), 'the form is closed or shows an error');
    });
    if (!saved || (await form.count()) === 0) return;
    const shown = (await form.locator(NEW_FAILED).allInnerTexts()).join(' ').replace(/\s+/g, ' ').trim();
    throw new Error(`The form was not saved: ${shown || 'it is still open'}.`);
  }

  /**
   * Runs a transit of the item of the current screen, `transit:<id>`, with the values of
   * its payload in its dialog, or confirmed in its dialog when the specs confirm it, and
   * waits until it is done (the transit is no longer offered) or shows an error.
   */
  async transit(id: string, payload?: Values): Promise<void> {
    const button = this.screen().locator(bz('transit', id));
    const failed = this.page.locator(NEW_FAILED);
    await this.seen(this.page.locator('body'));
    await button.click();
    if (payload !== undefined) {
      await this.fill(payload);
      await this.submit();
    } else {
      await this.confirmTransit(async () => (await button.count()) === 0 || (await failed.count()) > 0);
    }
    await this.until(button, failed, `the transit ${id} is done or shows an error`);
  }

  /**
   * The current screen is this one: at its route (another screen may show next to it, such
   * as a list next to its card), with its state rendered.
   */
  async expectScreen(screen: ScreenId<P>): Promise<void> {
    const target = this.product.screens[screen];
    if (target === undefined) throw new Error(`The screen ${screen} is not in the specs.`);
    await expect(this.page.locator(bz('screen', screen))).toBeVisible();
    await expect
      .poll(() => new URL(this.page.url()).pathname, { message: `the route of the screen ${screen} (${target.route})` })
      .toMatch(routePattern(target.route));
    this.current = screen;
    await this.settled();
  }

  /** The item of the current screen has this status, `status:<id>`. */
  async expectStatus(status: string): Promise<void> {
    await expect(this.screen().locator(bz('status', status)).first()).toBeVisible();
  }

  /** The page shows this state, `state:<state>` (a screen kept hidden next to it does not count). */
  async expectState(state: State): Promise<void> {
    await expect(this.page.locator(bz('state', state)).filter({ visible: true }).first()).toBeVisible();
  }

  /** The current screen, once loaded, does not offer this action. */
  async expectActionAbsent(id: string): Promise<void> {
    await this.settled();
    await expect(this.screen().locator(bz('action', id))).toHaveCount(0);
  }

  /**
   * The user may not change the field: read-only (or not there) in the open form; on a card
   * without a form, the card has no edit (`action:edit`), or its edit has the field
   * read-only (the edit is opened and cancelled).
   */
  async expectFieldReadonly(field: string): Promise<void> {
    await this.settled();
    const form = this.form();
    if ((await form.count()) > 0) {
      await this.expectReadonlyIn(form, field);
      return;
    }
    const screen = this.screen();
    const edit = screen.locator(bz('action', 'edit'));
    if ((await edit.count()) === 0) {
      const value = screen.locator(bz('field', field)).first();
      await this.reveal(value);
      await expect(value).toBeVisible();
      return;
    }
    await edit.click();
    await expect(form).toBeVisible();
    await this.expectReadonlyIn(form, field);
    await form.locator(bz('action', 'cancel')).click();
    await expect(form).toHaveCount(0);
  }

  /**
   * The user may not see the field: the current screen, once loaded, has no `field:<name>`
   * (a card, the open form) and no cell `cell:<name>` (a list).
   */
  async expectFieldAbsent(field: string): Promise<void> {
    await this.settled();
    await expect(this.screen().locator(`${bz('field', field)}, ${bz('cell', field)}`)).toHaveCount(0);
    await expect(this.form().locator(bz('field', field))).toHaveCount(0);
  }

  /**
   * The fields of the current card show these texts: the text of each `field:<name>` contains
   * its text (a file: its name).
   */
  async expectValues(values: Readonly<Record<string, string>>): Promise<void> {
    await this.settled();
    for (const [name, value] of Object.entries(values)) {
      const field = this.screen().locator(bz('field', name)).first();
      await this.reveal(field);
      await expect(field).toContainText(value);
    }
  }

  /** The list of the current screen has this number of rows, `row:<id>`. */
  async expectRows(count: number): Promise<void> {
    await this.settled();
    await expect(this.screen().locator('[data-bz^="row:"]')).toHaveCount(count);
  }

  /**
   * The tile of the current dashboard shows this number, `tile:<id>` (its `data-value`): the count
   * of its items, or the number of its `value` (`2.5`).
   */
  async expectTile(id: string, value: number): Promise<void> {
    await this.settled();
    await expect(this.screen().locator(bz('tile', id))).toHaveAttribute('data-value', String(value));
  }

  /**
   * The day of the calendar of the current screen has this number of items, `day:<date>` (its
   * `data-count`): the calendar (`calendar:<entity>`, the days it shows from `data-from` to
   * `data-to`) is first moved to the period of the day (`action:previous-period`,
   * `action:next-period`). The day is `YYYY-MM-DD`, or `today`, `today+<n>`, `today-<n>` days
   * from the day of the run, in UTC as the browser of the tests (`day`).
   */
  async expectDay(day: string, count: number): Promise<void> {
    const date = dayOfRun(day);
    await this.settled();
    const calendar = this.screen().locator('[data-bz^="calendar:"]');
    for (;;) {
      const from = (await calendar.getAttribute('data-from')) ?? '';
      const to = (await calendar.getAttribute('data-to')) ?? '';
      if (date >= from && date <= to) break;
      await calendar.locator(bz('action', date < from ? 'previous-period' : 'next-period')).click();
      await expect(calendar).not.toHaveAttribute('data-from', from);
      await this.settled();
    }
    await expect(calendar.locator(bz('day', date))).toHaveAttribute('data-count', String(count));
  }

  /** A field shows a validation error, `error:<name>`. */
  async expectError(field: string): Promise<void> {
    await expect(this.page.locator(bz('error', field)).filter({ visible: true }).first()).toBeVisible();
  }

  /**
   * The user has a notification whose text contains this text, that came since this test
   * started (its time, `<time datetime>`; one of a previous run does not count): the bell
   * (`action:notifications`) opens the list of the notifications (`list:notifications`),
   * which waits for it (`notification:<key>`), and is closed again.
   */
  async expectNotification(text: string): Promise<void> {
    const bell = this.page.locator(bz('action', 'notifications')).filter({ visible: true }).first();
    await bell.click();
    const list = this.page.locator(bz('list', 'notifications'));
    const notifications = list.locator('[data-bz^="notification:"]').filter({ hasText: text });
    await expect
      .poll(
        () =>
          notifications.evaluateAll(
            (elements, started) =>
              elements.some((element) => Date.parse(element.querySelector('time')?.dateTime ?? '') >= started),
            this.started,
          ),
        { message: `a notification with the text ${text} since the test started` },
      )
      .toBe(true);
    await this.page.keyboard.press('Escape');
    await expect(list).toHaveCount(0);
  }

  /**
   * Switches the language of the interface to a language of the backend (`LANGUAGES` of the
   * contract): the button of the layout, `action:language`, until its `data-value` is the
   * code. Not a step of the scenarios: the tests of the product (`e2e/custom/`) use it.
   */
  async language(code: string): Promise<void> {
    const toggle = this.page.locator(bz('action', 'language')).filter({ visible: true }).first();
    await expect(toggle).toBeVisible();
    // a button that goes through the languages: as many clicks as there are languages at most
    for (let clicks = 0; clicks < MAX_LANGUAGES; clicks += 1) {
      const current = await toggle.getAttribute('data-value');
      if (current === code) return;
      await toggle.click();
      await expect(toggle).not.toHaveAttribute('data-value', current ?? '');
    }
    await expect(toggle).toHaveAttribute('data-value', code);
  }

  private async expectReadonlyIn(form: Locator, field: string): Promise<void> {
    const control = form.locator(bz('field', field));
    if ((await control.count()) > 0) await expect(control).not.toBeEditable();
  }

  /** The item that `openItem` opens. */
  private async row(where: Values, { recent, created }: { recent?: string | undefined; created: boolean }): Promise<Locator> {
    if (created && this.created.size === 0) throw new Error('This test created no item: no submit of it answered with a create.');
    await this.settled();
    const lists = this.screen().locator('[data-bz^="list:"]');
    const list =
      recent !== undefined ? this.screen().locator(bz('recent', recent)) : (await lists.count()) > 0 ? lists.first() : this.screen();
    const shown = await this.rowOnPage(list, where, created);
    if (shown) return shown;
    const search = list.locator(bz('field', '$search'));
    if ((await search.count()) > 0) {
      const texts = Object.values(where).flatMap((it) => (typeof it === 'string' || typeof it === 'number' ? [String(it).trim()] : []));
      for (const text of new Set(texts.filter(Boolean))) {
        await this.searchList(list, search, text);
        const found = await this.rowOnPages(list, where, created);
        if (found) return found;
      }
      await this.searchList(list, search, '');
    }
    const found = await this.rowOnPages(list, where, created);
    if (found) return found;
    const which = created ? 'that this test created' : 'of the list';
    throw new Error(`No row ${which} of the screen ${String(this.current)} has the texts ${JSON.stringify(where)}.`);
  }

  /** The first row of the list on its page whose cells have the texts (with `created`, one that this test created), or null. */
  private async rowOnPage(list: Locator, where: Values, created: boolean): Promise<Locator | null> {
    let rows = list.locator('[data-bz^="row:"]');
    if (created) rows = rows.and(this.page.locator([...this.created].map((id) => bz('row', id)).join(', ')));
    for (const [name, value] of Object.entries(where)) {
      rows = rows.filter({ has: this.page.locator(bz('cell', name)).filter({ hasText: exactly(value) }) });
    }
    return (await rows.count()) > 0 ? rows.first() : null;
  }

  /** The row on the page of the list or on its next pages (more items of a board), or null. */
  private async rowOnPages(list: Locator, where: Values, created: boolean): Promise<Locator | null> {
    const rows = list.locator('[data-bz^="row:"]');
    const next = list.locator(bz('action', 'next-page'));
    const more = list.locator(bz('action', 'more'));
    for (;;) {
      const row = await this.rowOnPage(list, where, created);
      if (row) return row;
      if ((await next.count()) > 0 && !(await next.isDisabled())) {
        const shown = await rows.first().getAttribute('data-bz');
        await next.click();
        // the rows of the next page, loaded
        await expect.poll(() => rows.first().getAttribute('data-bz'), { message: 'the next page of the list' }).not.toBe(shown);
      } else if ((await more.count()) > 0) {
        const listed = await rows.count();
        await more.first().click();
        await expect.poll(() => rows.count(), { message: 'more items of the board' }).toBeGreaterThan(listed);
      } else return null;
      await this.listSettled(list);
    }
  }

  /**
   * Searches the list and waits for the rows of the search: the list marks the search of
   * its rows (`data-search`) and is busy until they are loaded.
   */
  private async searchList(list: Locator, input: Locator, text: string): Promise<void> {
    await input.fill(text);
    if (text) await expect(list).toHaveAttribute('data-search', text);
    else await expect(list).not.toHaveAttribute('data-search');
    await this.listSettled(list);
  }

  /** Searches the list of the current screen (`field:$search`) and waits for its rows. */
  async search(text: string): Promise<void> {
    await this.settled();
    const list = this.screen().locator('[data-bz^="list:"]').first();
    await this.searchList(list, list.locator(bz('field', '$search')), text);
  }

  /** Waits until the list is no longer busy and nothing on the page loads. */
  private async listSettled(list: Locator): Promise<void> {
    await expect(list).not.toHaveAttribute('aria-busy', 'true');
    await expect(this.page.locator(bz('state', 'loading'))).toHaveCount(0);
  }

  /**
   * Waits until the current screen has rendered a state and nothing on the page loads. A
   * custom screen renders the states of its primitive too, as a generated one does.
   */
  private async settled(): Promise<void> {
    await expect(this.screen().locator('[data-bz^="state:"]').first())
      .toBeAttached()
      .catch(() => {
        throw new Error(
          'The current screen renders no state (data-bz="state:<state>"): render the marks of the states of its primitive, with StatePanel or the components of the resource.',
        );
      });
    await expect(this.page.locator(bz('state', 'loading'))).toHaveCount(0);
  }

  /**
   * Shows the tab of the card that has the element when it is in a hidden tab panel: the tab
   * (`tab:<id>`, `role="tab"`) whose `aria-controls` is the panel, until it is selected. The
   * panels of the tabs stay in the page while they are hidden, so that a step finds what it
   * acts on whatever the tab shown.
   */
  private async reveal(element: Locator): Promise<void> {
    const first = element.first();
    await expect(first).toBeAttached();
    const panel = first.locator('xpath=ancestor::*[@role="tabpanel"][1]');
    if ((await panel.count()) === 0 || (await panel.isVisible())) return;
    const tab = this.page.locator(`[role="tab"][aria-controls=${JSON.stringify((await panel.getAttribute('id')) ?? '')}]`);
    await tab.click();
    await expect(tab).toHaveAttribute('aria-selected', 'true');
  }

  /**
   * Marks the failures shown in the scope, so that a step waits for its own: those of a
   * previous submit stay on the page until the next one is sent.
   */
  private async seen(scope: Locator): Promise<void> {
    await scope.locator(FAILED).evaluateAll((elements, attribute) => {
      for (const element of elements) element.setAttribute(attribute, '');
    }, SEEN);
  }

  /**
   * Confirms the transit just run in its dialog once it shows (`CONFIRM_TRANSIT`), unless it
   * is `done` first: the transits that the specs do not confirm run at once.
   */
  private async confirmTransit(done: () => Promise<boolean>): Promise<void> {
    const confirm = this.page.locator(CONFIRM_TRANSIT);
    await expect
      .poll(async () => (await confirm.count()) > 0 || (await done()), { message: 'the transit is confirmed, done or shows an error' })
      .toBe(true);
    if ((await confirm.count()) > 0) await confirm.click();
  }

  /**
   * Runs `run` and records the items that the requests of the page created meanwhile: the
   * answers 201 in JSON of a POST (a create of the backend), their item in `data.id`.
   */
  private async recordCreated(run: () => Promise<void>): Promise<void> {
    const answers: Response[] = [];
    const listen = (response: Response) => {
      const json = (response.headers()['content-type'] ?? '').includes('json');
      if (response.status() === 201 && response.request().method() === 'POST' && json) answers.push(response);
    };
    this.page.on('response', listen);
    try {
      await run();
    } finally {
      this.page.off('response', listen);
    }
    for (const answer of answers) {
      const { data } = (await answer.json()) as { data?: { id?: string | number } };
      if (data?.id !== undefined) this.created.add(String(data.id));
    }
  }

  /** Waits until `gone` is no longer on the page or `failed` is. */
  private async until(gone: Locator, failed: Locator, message: string): Promise<void> {
    await expect
      .poll(async () => (await gone.count()) === 0 || (await failed.count()) > 0, { message })
      .toBe(true);
  }
}

