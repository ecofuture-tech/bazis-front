"""
The end-to-end tests of the scenarios of product.yaml (`bazis_front e2e`): a Playwright test
per scenario in `frontend/e2e/generated/<scenario>.spec.ts`, and `product.ts` there, the
part of the specs that the helpers of the frontend (`e2e/bazis/`, the asset `playwright`)
read at run time: the test users of the roles and the routes of the screens.

The steps are those of the walk of `scenarios.py`, the one that `bazis_front check`
checks; each becomes calls of the helpers, which act through the `data-bz` marks of the
screens. The text depends on the specs only: `--check` and `front.W003` render it again and
compare it byte for byte, without Node. A scenario of several sessions (`as`) has a variable
for each (`app` for the role of the scenario, `as<Role>` for the others, `sessionAs`), and a
value that it remembers (`remember`) and a next step takes is the constant `$<name>`. The
lock records the hashes of the specs the tests were generated from and their own (`e2e`):
the files of a scenario that was removed are deleted by the next generation.
"""

import json
from pathlib import Path

from ..contract.typescript import constant
from ..vendor import lock as frontend_lock
from .names import session_name
from .scenarios import Step, variable
from .validate import PRODUCT_FILE, SPEC_DIR, Specs, screen_files


GENERATED_DIR = 'e2e/generated'
PRODUCT_TS = f'{GENERATED_DIR}/product.ts'

#: the keys of an `expect` step, in the order of their checks, with their helper (called
#: once for each entry of the keys of `EXPECT_ENTRIES`)
EXPECT = (
    ('screen', 'expectScreen'),
    ('status', 'expectStatus'),
    ('state', 'expectState'),
    ('action_absent', 'expectActionAbsent'),
    ('transit_absent', 'expectTransitAbsent'),
    ('field_readonly', 'expectFieldReadonly'),
    ('field_absent', 'expectFieldAbsent'),
    ('values', 'expectValues'),
    ('rows', 'expectRows'),
    ('tile', 'expectTile'),
    ('day', 'expectDay'),
    ('error', 'expectError'),
    ('notification', 'expectNotification'),
)
EXPECT_ENTRIES = ('tile', 'day')


def header(source: str) -> str:
    return (
        f'// Generated by `manage.py bazis_front e2e` from {source}:\n'
        '// never edit it, change the specs and generate it again.\n'
    )


def string(value: str) -> str:
    """
    A TypeScript string literal in single quotes.
    """
    inner = json.dumps(value, ensure_ascii=False)[1:-1].replace('\\"', '"').replace("'", "\\'")
    return f"'{inner}'"


def literal(value, remembered: bool = False) -> str:
    """
    The TypeScript literal of a scalar of the specs, or of an object of them (the values of
    the fields, whose names are identifiers) or a list of them (the labels of the items of a
    to-many relationship), on one line; with `remembered`, a value `$<name>` of the object is
    the constant of the value that `remember` took (`fill`, `values`, `payload`), as is one of
    the objects `where` and `payload` of any object (`open_item`, `select`, `move`).
    """
    if isinstance(value, dict):
        if not value:
            return '{}'
        return '{ ' + ', '.join(
            f'{key}: {f"${variable(item)}" if remembered and variable(item) else literal(item, key in ("where", "payload"))}'
            for key, item in value.items()
        ) + ' }'
    if isinstance(value, list):
        return '[' + ', '.join(literal(item) for item in value) + ']'
    if isinstance(value, str):
        return string(value)
    return json.dumps(value)


def flow(value) -> str:
    """
    A value of a step as YAML in flow style, for the title of its `test.step`.
    """
    if isinstance(value, dict):
        return '{' + ', '.join(f'{key}: {flow(item)}' for key, item in value.items()) + '}'
    if isinstance(value, list):
        return '[' + ', '.join(flow(item) for item in value) + ']'
    if isinstance(value, str):
        return value or "''"
    return json.dumps(value)


def uploaded(payload: dict | None, files: tuple[str, ...]) -> tuple[dict | None, dict]:
    """The values of a payload that its dialog fills, and the files that it uploads (`Step.files`)."""
    if payload is None:
        return None, {}
    return {k: v for k, v in payload.items() if k not in files}, {k: v for k, v in payload.items() if k in files}


def calls(step: Step, screens: bool = False, app: str = 'app') -> list[str]:
    """
    The calls of the helpers that run a step in the session of the variable `app`; with the
    screens generated from the specs (`screens`), the dialog of a destroy action is confirmed:
    that of a generated screen must be shown; a custom screen may show none (`optional`).
    """
    name, value = step.name, step.value
    result = [f"{app}.action('edit')"] if step.edit else []
    if name == 'open':
        result.append(f'{app}.open({string(value)})')
    elif name in ('open_item', 'select', 'move'):
        helper = 'openItem' if name == 'open_item' else name
        if step.files:
            payload, files = uploaded(value['payload'], step.files)
            value = {**value, 'payload': payload, 'files': files}
        # the item that the test created, never one of a previous run with the same texts
        result.append(f'{app}.{helper}({literal({**value, "created": True} if step.created else value)})')
    elif name in ('action', 'bulk'):
        result.append(f'{app}.{name}({string(value)})')
        if step.confirm and screens:
            optional = ', { optional: true }' if step.confirm == 'optional' else ''
            result.append(f'{app}.confirm({string(value)}{optional})')
    elif name == 'fill':
        result.append(f'{app}.fill({literal(value, True)})')
    elif name == 'upload':
        result.append(f'{app}.upload({string(value["field"])}, {string(value["file"])})')
    elif name == 'submit':
        # a submit that the next step does not expect to fail must save
        result.append(f'{app}.submit()' if step.failing else f'{app}.submit({{ saved: true }})')
    elif name == 'transit':
        transit = {'id': value} if isinstance(value, str) else value
        payload, files = uploaded(transit.get('payload'), step.files)
        arguments = f', {literal(payload, True)}' if payload is not None else ''
        arguments += f', {literal(files)}' if files else ''
        result.append(f'{app}.transit({string(transit["id"])}{arguments})')
    elif name == 'expect':
        for key, helper in EXPECT:
            if key in EXPECT_ENTRIES:
                result += [f'{app}.{helper}({string(it)}, {literal(count)})' for it, count in value.get(key, {}).items()]
            elif key in value:
                result.append(f'{app}.{helper}({literal(value[key], key == "values")})')
    else:
        raise ValueError(f'unknown step {name}')
    if step.then is not None:
        result.append(f'{app}.expectScreen({string(step.then)})')
    return result


def render_scenario(scenario: dict, steps: list[Step], screens: bool) -> str:
    """
    The test of a scenario: a `test.step` for each step, in the session of the role of the
    scenario (`app`, `loginAs`) or of the last `as` (`sessionAs` opens it the first time, in
    `test` of the helpers, which closes it); a `remember` reads the values of the answer
    (`answer`) and declares the constants of those that a next step takes (`Step.taken`): the
    lint of the frontend refuses a constant that nothing uses.
    """
    role = scenario['role']
    sessions = {role: 'app'}
    # the tests of several sessions are those of the helpers, which close the sessions
    imports = (
        ["import { loginAs, sessionAs, test } from '../bazis';"]
        if any(step.name == 'as' and step.value != role for step in steps)
        else ["import { test } from '@playwright/test';", '', "import { loginAs } from '../bazis';"]
    )
    lines = [
        header(f'the scenario `{scenario["id"]}` of {PRODUCT_FILE}'),
        *imports,
        '',
        "import { PRODUCT } from './product';",
        '',
        f'test({string(scenario["id"])}, async ({{ page }}) => {{',
        f'  const app = await loginAs(page, PRODUCT, {string(role)});',
    ]
    app = 'app'
    for step in steps:
        title = string(step.name if step.value == {} else f'{step.name}: {flow(step.value)}')
        if step.name == 'as':
            if step.value in sessions:
                app = sessions[step.value]
                lines.append(f'  await test.step({title}, () => {app}.page.bringToFront());')
            else:
                app = sessions[step.value] = session_name(step.value)
                lines.append(f'  const {app} = await test.step({title}, () => sessionAs(app, {string(step.value)}));')
        elif step.name == 'remember':
            answers = [f'{app}.answer({string(it)})' for it in step.value.values()]
            read = answers[0] if len(answers) == 1 else f'Promise.all([{", ".join(answers)}])'
            # the constants of the values taken, a hole in the array for another one
            names = [f'${it}' if it in step.taken else '' for it in step.value]
            while names and not names[-1]:
                names.pop()
            if not names:
                lines.append(f'  await test.step({title}, () => {read});')
            else:
                declared = names[0] if len(answers) == 1 else f'[{", ".join(names)}]'
                lines.append(f'  const {declared} = await test.step({title}, () => {read});')
        else:
            lines.append(f'  await test.step({title}, async () => {{')
            lines += [f'    await {call};' for call in calls(step, screens, app)]
            lines.append('  });')
    lines.append('});')
    return '\n'.join(lines) + '\n'


#: the documentation of `PRODUCT`, the part of the specs that the helpers read
PRODUCT_DOC = (
    f'What the helpers of e2e/bazis/ read of the specs: the user that a test logs in as for '
    f'each role of {PRODUCT_FILE} (`test_user`, null without one; `anonymous`: none, the test '
    f'does not log in), and the route of each screen of {SPEC_DIR}/screens/.'
)


def product(specs: Specs) -> dict:
    """
    `PRODUCT` of the helpers (`Product` of e2e/bazis/): the test users of the roles and the
    routes of the screens.
    """
    roles = {}
    for role in specs.product.get('roles', []):
        roles[role['id']] = {'username': role.get('test_user', {}).get('username')}
        if role.get('anonymous'):
            roles[role['id']]['anonymous'] = True
    screens = {screen_id: {'route': screen['route']} for screen_id, screen in specs.screens.items()}
    return {'roles': roles, 'screens': screens}


def render_product(specs: Specs) -> str:
    return '\n'.join([header(f'{SPEC_DIR}/'), constant(PRODUCT_DOC, 'PRODUCT', product(specs))])


def render(specs: Specs, screens: bool = False) -> dict[str, str]:
    """
    The generated files by their path in the frontend, from specs without errors; `screens`:
    whether the screens are generated from the specs (the key `screens` of the lock).
    """
    files = {PRODUCT_TS: render_product(specs)}
    for scenario in specs.product.get('scenarios', []):
        path = f'{GENERATED_DIR}/{scenario["id"]}.spec.ts'
        files[path] = render_scenario(scenario, specs.scenarios[scenario['id']], screens)
    return dict(sorted(files.items()))


def spec_hashes(root: Path) -> dict[str, str]:
    """
    The hashes of the specs that the tests are generated from, by their path in the product
    root: product.yaml and the screens.
    """
    return frontend_lock.file_hashes(root, [PRODUCT_FILE, *screen_files(root)])


def generated_path(frontend: Path, path: str) -> bool:
    """
    Whether a path of the lock is a file of `e2e/generated/` of the frontend: the generator
    never deletes or reports any other, whatever the lock lists.
    """
    return (frontend / path).resolve().is_relative_to((frontend / GENERATED_DIR).resolve())


def removed_files(frontend: Path, lock: dict, rendered: dict[str, str]) -> list[str]:
    """
    The generated files of the lock that the specs no longer generate and that still exist.
    """
    return sorted(
        path for path in lock.get('e2e', {}).get('generated', {})
        if path not in rendered and generated_path(frontend, path) and (frontend / path).is_file()
    )


def stale(root: Path, frontend: Path, lock: dict, rendered: dict[str, str]) -> list[str]:
    """
    Why the generated tests of the frontend differ from those of the specs, one message for
    each; empty when they are current. The files are compared byte for byte; those of the
    lock that the specs no longer generate are stale while they exist.
    """
    names = frontend_lock.stale_files(frontend, rendered)
    removed = removed_files(frontend, lock, rendered)
    if not names and not removed:
        return []
    problems = [
        f'The end-to-end tests of {frontend} are stale: '
        + ', '.join(
            [*names, *(f'{it} (of a scenario that no longer exists)' for it in removed)]
        )
        + '.'
    ]
    changed, edited = frontend_lock.generation_changes(
        lock.get('e2e', {}), spec_hashes(root), frontend, names
    )
    if changed:
        problems.append(f'The specs changed since they were generated: {", ".join(changed)}.')
    if edited:
        problems.append(f'Edited after they were generated: {", ".join(edited)}.')
    return problems


def write(root: Path, frontend: Path, lock: dict, rendered: dict[str, str]) -> list[str]:
    """
    Writes the generated tests, deletes those of the lock that the specs no longer generate
    and records the hashes of the specs and of the files in the lock. Returns the deleted
    paths.
    """
    removed = removed_files(frontend, lock, rendered)
    frontend_lock.write_files(frontend, rendered)
    for path in removed:
        (frontend / path).unlink()
    lock['e2e'] = frontend_lock.generation(spec_hashes(root), rendered)
    frontend_lock.write(frontend, lock)
    return removed
