"""
The screenshots of the screens (`bazis_front shots`), the visual check of a frontend:
`frontend/e2e/generated/shots.ts` shoots every screen of the specs as the first of its roles
(of the product without one), in each color mode of the theme, at the widths of the projects
of `playwright.shots.config.ts`, with the helper `shoot` of `e2e/bazis/shots.ts`, which checks
what each screen renders (the codes `V0xx` of `CODES` there) and writes its screenshot and
its result into `frontend/.scratch/shots/`; `collect` gathers the results into `report.json`.

A screen of an item (its route has an id) is reached through the first item of a screen
that opens it (`open` of a list, a board, a calendar; of the last items of a dashboard, in
their part `recent:<id>`), one for its role: a list first, one without a filter of its own
before a report; one that no such screen opens is not shot. The text of `shots.ts` depends on the specs only: `--check` and
`front.W008` render it again and compare it byte for byte, without Node, and the lock records
the hashes of the specs and of the file (`shots`). It is not a `.spec.ts`: `npm run e2e` does
not run it.
"""

import json
import os
import shutil
import subprocess
from pathlib import Path

from ..contract.typescript import constant
from ..vendor import lock as frontend_lock
from . import design, e2e
from .refs import screen_actions
from .validate import SPEC_DIR, THEME_FILE, TOKENS_FILE, Specs


SHOTS_TS = f'{e2e.GENERATED_DIR}/shots.ts'
CONFIG = 'playwright.shots.config.ts'
#: the screenshots and their results, in the frontend (ignored by Git)
OUTPUT_DIR = '.scratch/shots'
REPORT = 'report.json'

#: the code of a screen that was not shot (`CODES` of e2e/bazis/shots.ts)
NOT_SHOT = 'V001'


def header() -> str:
    return (
        f'// Generated by `manage.py bazis_front shots` from {SPEC_DIR}/:\n'
        '// never edit it, change the specs and generate it again.\n'
    )


def opens(screen: dict) -> dict[str, str | None]:
    """
    The screens of an item that the items of a screen open, each with the mark of the part
    of the screen whose items open it (`recent:<id>` of a dashboard), None for the screen.
    """
    section = screen.get(screen['primitive'], {})
    if screen['primitive'] == 'dashboard':
        parts: dict[str, str | None] = {}
        for it in section.get('recent', []):
            if 'open' in it:
                parts.setdefault(it['open'], f'recent:{it["id"]}')
        return parts
    return {section['open']: None} if 'open' in section else {}


def plan(specs: Specs) -> tuple[list[dict], dict[str, str]]:
    """
    The shots of the screens of the specs, by screen id (without the color mode), and the
    screens that are not shot with why.
    """
    roles = [it['id'] for it in specs.product.get('roles', [])]
    screens = sorted(specs.screens.items())
    # the screens that open an item: the lists first, those without a filter of their own
    # (all the items) before the reports
    parents = sorted(
        (it for it in screens if ':' not in it[1]['route']),
        key=lambda it: (it[1]['primitive'] != 'list', 'filter' in it[1].get('list', {}), it[0]),
    )
    shots, skipped = [], {}
    for screen_id, screen in screens:
        candidates = screen.get('roles') or roles or [None]
        role, via = candidates[0], None
        if ':' in screen['route']:
            opening = [(parent, data) for parent, data in parents if screen_id in opens(data)]
            # the first role of the screen that a screen opening its items is for
            role, via = next(
                (
                    (candidate, {'screen': parent, 'part': opens(data)[screen_id]})
                    for candidate in candidates
                    for parent, data in opening
                    if candidate is None or not data.get('roles') or candidate in data['roles']
                ),
                (None, None),
            )
            if via is None:
                skipped[screen_id] = (
                    'no list, board, calendar or dashboard of its roles opens its items'
                    if opening
                    else 'no list, board, calendar or dashboard of the specs opens its items'
                )
                continue
        creates = [
            it['id'] for _, it in screen_actions(screen) if it.get('primitive') == 'form' and it.get('mode') == 'create'
        ]
        shots.append({'screen': screen_id, 'role': role, 'via': via, 'creates': creates})
    return shots, skipped


def modes(specs: Specs) -> tuple[str, ...]:
    """
    The color modes of the theme of the specs.
    """
    return design.modes(specs.theme, design.effective_tokens(specs.theme, specs.tokens))


def render(specs: Specs) -> dict[str, str]:
    """
    `shots.ts` by its path in the frontend, from specs without errors.
    """
    shots, skipped = plan(specs)
    lines = [header()]
    lines += [f'// Not shot: {screen}: {why}.' for screen, why in skipped.items()]
    lines += [
        "import { test } from '@playwright/test';",
        '',
        "import { shoot } from '../bazis/shots';",
        '',
        constant(e2e.PRODUCT_DOC, 'PRODUCT', e2e.product(specs)),
    ]
    for mode in modes(specs):
        lines.append(f'test.describe({e2e.string(mode)}, () => {{')
        lines.append(f'  test.use({{ colorScheme: {e2e.string(mode)} }});')
        for shot in shots:
            value = e2e.literal({
                'screen': shot['screen'], 'role': shot['role'], 'mode': mode, 'via': shot['via'],
                'creates': shot['creates'],
            })
            lines += [
                '',
                f'  test({e2e.string(shot["screen"])}, async ({{ page }}, info) => {{',
                f'    await shoot(page, PRODUCT, {value}, info);',
                '  });',
            ]
        lines.append('});')
        lines.append('')
    return {SHOTS_TS: '\n'.join(lines)}


def spec_hashes(root: Path) -> dict[str, str]:
    """
    The hashes of the specs that `shots.ts` is generated from: those of the end-to-end tests
    and the design (its color modes).
    """
    return {**e2e.spec_hashes(root), **frontend_lock.file_hashes(root, [THEME_FILE, TOKENS_FILE])}


def stale(root: Path, frontend: Path, lock: dict, rendered: dict[str, str]) -> list[str]:
    """
    Why `shots.ts` of the frontend differs from that of the specs, one message for each;
    empty when it is current.
    """
    names = frontend_lock.stale_files(frontend, rendered)
    if not names:
        return []
    problems = [f'The screenshots of {frontend} are stale: {", ".join(names)}.']
    changed, edited = frontend_lock.generation_changes(lock.get('shots', {}), spec_hashes(root), frontend, names)
    if changed:
        problems.append(f'The specs changed since it was generated: {", ".join(changed)}.')
    if edited:
        problems.append(f'Edited after it was generated: {", ".join(edited)}.')
    return problems


def write(root: Path, frontend: Path, lock: dict, rendered: dict[str, str]) -> None:
    """
    Writes `shots.ts` and records the hashes of the specs and of the file in the lock.
    """
    frontend_lock.write_files(frontend, rendered)
    lock['shots'] = frontend_lock.generation(spec_hashes(root), rendered)
    frontend_lock.write(frontend, lock)


class NodeMissingError(Exception):
    """
    Node (npx) is not found: the screenshots cannot be taken.
    """


def run(frontend: Path) -> None:
    """
    Takes the screenshots: empties `.scratch/shots/` and runs Playwright with
    `playwright.shots.config.ts` in the frontend, its output on the output of the process. A
    failed test is the error V001 of its result, which `collect` reads.
    """
    npx = shutil.which('npx')
    if npx is None:
        raise NodeMissingError('Node (npx) is not found')
    output = frontend / OUTPUT_DIR
    shutil.rmtree(output, ignore_errors=True)
    output.mkdir(parents=True)
    command = [npx, '--no-install', 'playwright', 'test', '--config', CONFIG]
    environment = {**os.environ, 'BAZIS_SHOTS_DIR': str(output)}
    subprocess.run(command, cwd=frontend, env=environment, check=False)


def collect(frontend: Path, specs: Specs) -> dict:
    """
    The report of the screenshots, written to `.scratch/shots/report.json`: the results that
    `shoot` wrote, by screen, role, color mode and width, with the number of their errors and
    warnings. A shot of the specs without a result at a width of the run (or at all) is the
    error V001: its test did not finish.
    """
    output = frontend / OUTPUT_DIR
    results = [
        json.loads(path.read_text(encoding='utf-8')) for path in output.glob('*.json') if path.name != REPORT
    ]
    widths = sorted({it['width'] for it in results}) or [None]
    done = {(it['screen'], it['role'], it['mode'], it['width']) for it in results}
    shots, _skipped = plan(specs)
    for mode in modes(specs):
        for shot in shots:
            for width in widths:
                if (shot['screen'], shot['role'], mode, width) not in done:
                    results.append({
                        'screen': shot['screen'], 'role': shot['role'], 'mode': mode, 'width': width, 'file': None,
                        'issues': [{
                            'code': NOT_SHOT, 'severity': 'error', 'selector': f'[data-bz="screen:{shot["screen"]}"]',
                            'message': 'No result: its test did not finish (see the output of Playwright).',
                        }],
                    })
    results.sort(key=lambda it: (it['screen'], it['mode'], it['width'] or 0, it['role'] or ''))
    issues = [issue for it in results for issue in it['issues']]
    report = {
        'errors': sum(it['severity'] == 'error' for it in issues),
        'warnings': sum(it['severity'] == 'warning' for it in issues),
        'shots': results,
    }
    (output / REPORT).write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    return report


def read_report(frontend: Path) -> dict | None:
    """
    The report of the last screenshots; None when there is none or it cannot be read.
    """
    try:
        return json.loads((frontend / OUTPUT_DIR / REPORT).read_text(encoding='utf-8'))
    except (OSError, ValueError):
        return None
