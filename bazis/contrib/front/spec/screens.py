def lazy_screen(data: dict) -> Const:
    custom = data.get('custom')
    if isinstance(custom, dict):
        source, name = custom['module'], custom['export']
    elif custom:
        source, name = f'@/screens/{data["id"]}', component_name(data['id'])
    else:
        source, name = f'@/screens/generated/{data["id"]}', component_name(data['id'])
    load = Call(f'import({quote(source)}).then', [Arrow(['module'], Raw(f'module.{name}'))])
    return Const(component_name(data['id']), Call('lazyScreen', [Arrow([], load)]))


def route_element(product: Product, data: dict, nested: list[dict]) -> Jsx:
    element = Jsx(component_name(data['id']))
    # the home is `index` but when it has the routes of its cards: an index route has no children
    attrs = [Attr('index')] if data['route'] == HOME_ROUTE and not nested else [Attr('path', data['route'])]
    if nested:
        attrs.append(Attr('element', Jsx('ListCardLayout', [Attr('list', element)])))
        children = [
            Jsx('Route', [Attr('path', it['route']), Attr('element', Jsx(component_name(it['id'])))]) for it in nested
        ]
        return Jsx('Route', attrs, children)
    attrs.append(Attr('element', element))
    return Jsx('Route', attrs)


def render_routes(product: Product) -> str:
    code = Code()
    code.use('react-router', 'Route')
    code.use('@/app/lazy', 'lazyScreen')
    screens = sorted(product.screens.values(), key=lambda it: it['id'])
    nested = {it['id']: product.host(it) for it in screens if it['primitive'] == 'card'}
    hosted: dict[str, list[dict]] = {}
    for card_id, layout in nested.items():
        if layout is not None:
            hosted.setdefault(layout['id'], []).append(product.screens[card_id])
    if hosted:
        code.use('@/bazis/ui/app-shell', 'ListCardLayout')
    # the public screens and those of a session, a card with the list in whose layout it is
    # (S045: both are public or neither)
    routes: dict[bool, list[Jsx]] = {True: [], False: []}
    for it in screens:
        if nested.get(it['id']) is None:
            routes[product.public(it)].append(route_element(product, it, hosted.get(it['id'], [])))
    home_screen = next((it for it in screens if it['route'] == HOME_ROUTE), None)
    first = first_link(product)
    if home_screen is None and first is not None:
        code.use('react-router', 'Navigate')
        redirect = Jsx('Navigate', [Attr('to', first['route']), Attr('replace')])
        routes[product.public(first)].insert(0, Jsx('Route', [Attr('index'), Attr('element', redirect)]))
    # a guest who opens `/` lands on the first public link, unless `/` is public itself
    home = home_screen or first
    guest_home = None if home is not None and product.public(home) else first_public_link(product)
    lazy = '\n'.join(printed(lazy_screen(it).doc()) for it in screens)

    def fragment(name: str, items: list[Jsx]) -> str:
        return printed(Const(name, Jsx('', [], items) if items else Raw('null'), exported=True).doc())

    return module(
        header(f'{SPEC_DIR}/screens/'),
        *code.imports(),
        doc_comment(
            'The screens of the specs, each loaded with its own chunk when its route is first shown: the',
            'generated ones and those written by hand (`custom`).',
        ) + '\n' + lazy if lazy else '',
        doc_comment(
            'The routes of the public screens (an anonymous role in their `roles`), outside `RequireSession`',
            'of src/app/router.tsx: shown without a session; null without them.',
        ) + '\n' + fragment('PUBLIC_ROUTES', routes[True]),
        doc_comment(
            'The routes of the other screens, inside `RequireSession` of src/app/router.tsx: a card whose',
            'route is that of a list followed by `/:id` beside the list or in its place (`ListCardLayout`);',
            '`/` without a screen leads to the first link of the navigation.',
        ) + '\n' + fragment('SCREEN_ROUTES', routes[False]),
        doc_comment(
            'The route that a user without a session who opens `/` is led to: the first public link of the',
            'navigation, null when `/` is public itself or no link is.',
        ) + '\n' + printed(
            Const('GUEST_HOME', Str(guest_home) if guest_home else Raw('null'), exported=True, type='string | null').doc()
        ),
    )


def default_navigation(product: Product) -> list[dict]:
    """
    The links without `navigation` in product.yaml: the home, the other dashboards, then of
    each entity in their order its lists, its boards, its calendars, its reports (a list
    with a filter) and the forms of its custom actions; never a screen of an item, a form of
    the items, or one with `nav: false`.
    """
    shown = [
        it for it in sorted(product.screens.values(), key=lambda it: it['id'])
        if ':' not in it['route'] and (it['primitive'] != 'form' or action_form(it) is not None) and it.get('nav') is not False
    ]
    links = [it for it in shown if it['route'] == HOME_ROUTE]
    links += [it for it in shown if it['primitive'] == 'dashboard' and it['route'] != HOME_ROUTE]
    for entity_id in product.entities:
        of = [it for it in shown if it.get('entity') == entity_id]
        links += [it for it in of if it['primitive'] == 'list' and 'filter' not in it['list']]
        links += [it for it in of if it['primitive'] == 'board']
        links += [it for it in of if it['primitive'] == 'calendar']
        links += [it for it in of if it['primitive'] == 'list' and 'filter' in it['list']]
        links += [it for it in of if it['primitive'] == 'form']
    return [{'screen': it['id']} for it in links]


def linked_screens(product: Product) -> list[dict]:
    """The screens of the links of the navigation, in their order, the groups expanded."""
    return [
        product.screens[link['screen']]
        for item in product.specs.product.get('navigation', default_navigation(product))
        for link in (item['items'] if 'group' in item else [item])
    ]


def first_link(product: Product) -> dict | None:
    """The screen of the first link of the navigation (of its first group), None without any."""
    return next(iter(linked_screens(product)), None)


def first_public_link(product: Product) -> str | None:
    """The route of the first link of the navigation that a guest sees, None without any."""
    return next((it['route'] for it in linked_screens(product) if product.public(it)), None)


def nav_item(code: Code, product: Product, link: dict, at: tuple) -> Obj:
    """
    The item of the link at a path of product.yaml, shown once the backend allows what it
    requires: to view the items of the entity of its screen (and filter them by the fields of
    a report, add one with `requires.can: add`), the form of a custom action its action (its
    key in the contract, `customActionKey`); at once a screen without an entity and the public
    form of an action.
    """
    data = product.screens[link['screen']]
    if 'label' in link:
        label = t(link['label'], text_key('', product.specs.product, (*at, 'label')))
    else:
        label = text(data, 'title') or Str(data['id'])
    props = [('screen', Str(data['id'])), ('label', label), ('to', Str(data['route']))]
    if data['route'] == HOME_ROUTE:
        props.append(('end', Raw('true')))
    icon = link.get('icon') or default_icon(product, data)
    if icon is not None:
        code.use('lucide-react', icon_name(icon))
        props.append(('icon', Raw(icon_name(icon))))
    # the form of an action requires its action, by its key in the contract (`action_<method>`,
    # what `custom_actions` of the list has, not the name in the path); a public one, nothing:
    # the backend checks the action of a guest
    form = action_form(data)
    if 'entity' in data and not (form is not None and product.public(data)):
        code.use('./entities', 'ENTITIES')
        entity = data['entity']
        member = f'.{entity}' if re.fullmatch(r'[A-Za-z_$][\w$]*', entity) else f'[{quote(entity)}]'
        path = f'ENTITIES{member}.path'
        requires = [('path', Raw(path))]
        if form is not None:
            code.use('@/bazis/ui/resource', 'customActionKey')
            requires.append(('can', Raw(f'customActionKey({path}, {quote(form["action"])})')))
        elif link.get('requires', {}).get('can') == 'add':
            requires.append(('can', Str('add')))
        if data['primitive'] == 'list' and 'filter' in data['list']:
            requires.append(('filters', Arr([Str(it) for it in data['list']['filter']])))
        props.append(('requires', Obj(requires)))
    if product.public(data):
        props.append(('public', Raw('true')))
    return Obj(props)


def default_icon(product: Product, data: dict) -> str | None:
    if data['route'] == HOME_ROUTE:
        return HOME_ICON
    primitive = data['primitive']
    if primitive == 'board':
        return BOARD_ICON
    if primitive == 'calendar':
        return CALENDAR_ICON
    if primitive == 'list' and 'filter' in data['list']:
        return REPORT_ICON
    return product.icons.get(data.get('entity'))


def render_navigation(product: Product) -> str:
    code = Code()
    code.use('@/bazis/i18n', 'type Translate')
    code.use('@/bazis/ui/app-shell', 'type NavEntry')
    spec = product.specs.product
    entries = []
    for i, item in enumerate(spec.get('navigation', default_navigation(product))):
        if 'group' in item:
            label = t(item['title'], text_key('', spec, ('navigation', i, 'title')))
            entries.append(Obj([
                ('group', Str(item['group'])), ('label', label),
                ('items', Arr([
                    nav_item(code, product, it, ('navigation', i, 'items', j)) for j, it in enumerate(item['items'])
                ])),
            ]))
        else:
            entries.append(nav_item(code, product, item, ('navigation', i)))
    navigation = Function('navigation', 't: Translate', Block([Return(Arr(entries))]), returns='readonly NavEntry[]')
    return module(
        header(f'the navigation of {PRODUCT_FILE}'),
        *code.imports(),
        doc_comment(
            'The links of the navigation (`nav:<screen>`), labelled by their `label` or the titles of',
            'their screens in the language of the interface, each shown once the backend allows the',
            'user what it `requires`; without a session, only those of the public screens (`public`).',
        ) + '\n' + printed(navigation.doc()),
    )


