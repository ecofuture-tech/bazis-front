"""
The screens generated from the specs (`bazis_front screens`), in
`frontend/src/screens/generated/`: a component per screen of `spec/screens/` that is not
`custom` (`<id>.tsx`, composed from the components as the spec says), and what the template
imports from there: the routes of every screen (`routes.tsx`, the custom ones too), the
navigation (`navigation.ts`), the texts of the specs in the languages of the product
(`messages.ts`, under the dictionaries of the product), its name (`product.ts`), the
entities (`entities.ts`), the routes by screen (`screens.ts`), the providers and the tools
of the layout that the packages and the fields need (`providers.tsx`, `tools.tsx`).

The code is that of a screen written by hand, in the style of prettier (`tsx.py`), and
depends on the specs only: `--check` and `front.W010` render it again and compare it byte
for byte, without Node. The lock records the hashes of the specs it was generated from and
its own (`screens`): a file edited since is not overwritten without `--force`, and the files
of a screen that is no longer generated are deleted. The components that the code imports
are copied into the frontend when it lacks them (`copy.add_assets`).
"""

