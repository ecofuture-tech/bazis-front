def header(source: str) -> str:
    return (
        f'// Generated by `manage.py bazis_front screens` from {source}:\n'
        '// never edit it, change the specs and generate it again.'
    )


def doc_comment(*lines: str) -> str:
    """A comment of documentation: on one line for one line of text."""
    if len(lines) == 1:
        return f'/** {lines[0]} */'
    return '\n'.join(['/**', *(f' * {it}' if it else ' *' for it in lines), ' */'])


def icon_name(icon: str) -> str:
    """The export of lucide-react of an icon, `<Name>Icon`: never the name of a component."""
    return pascal(icon) + 'Icon'


class Texts:
    """
    The texts of the specs in the dictionaries of the languages of the product
    (`GENERATED_MESSAGES`), each by a key of its place in the specs
    (`screens.<id>.card.sections.<section>.title`): a text in words is in the default
    language; a map gives each language its own, and the default language the text of the
    first language of the product that the map has when it lacks it (the others fall back to
    the default at run time). A key of the dictionaries (`TEXT_KEY`) is the product's.
    """

    def __init__(self, product: dict):
        languages = product.get('languages') or []
        self.default = product.get('language') or (languages[0] if languages else 'en')
        self.languages = languages or [self.default]
        self.messages: dict[str, dict[str, str]] = {it: {} for it in self.languages}

    def add(self, key: str, value) -> None:
        if isinstance(value, str):
            if not TEXT_KEY.fullmatch(value):
                self.messages[self.default][key] = value
            return
        for language in self.languages:
            if language in value:
                self.messages[language][key] = value[language]
        if self.default not in value:
            first = next((value[it] for it in self.languages if it in value), next(iter(value.values())))
            self.messages[self.default][key] = first


def texts(specs: Specs) -> Texts:
    """The texts of product.yaml and of the screens."""
    result = Texts(specs.product)
    for at, value in document_texts(specs.product, PRODUCT_SCHEMA):
        result.add(text_key('', specs.product, at), value)
    for screen_id, data in specs.screens.items():
        for at, value in document_texts(data, SCREEN_SCHEMA):
            result.add(text_key(screen_prefix(screen_id), data, at), value)
    return result


def message_key(value, key: str) -> Str:
    """The key of a text of the specs in the dictionaries: the text when it is one, else its own key."""
    return Str(value if isinstance(value, str) and TEXT_KEY.fullmatch(value) else key)


def t(value, key: str) -> Call:
    """The translation of a text of the specs: its key, or the key that it is."""
    return Call('t', [message_key(value, key)])


def text(screen: dict, *path) -> Call | None:
    """The translation of the text at a path of a screen, None without it."""
    node = screen
    for step in path:
        if isinstance(node, dict) and step in node or isinstance(node, list) and isinstance(step, int):
            node = node[step]
        else:
            return None
    return t(node, text_key(screen_prefix(screen['id']), screen, path))


class Code:
    """The imports of a module being written and its declarations."""

    def __init__(self):
        self.entries: dict[str, list[str]] = {}

    def use(self, source: str, *names: str) -> None:
        self.entries.setdefault(source, []).extend(names)

    def imports(self) -> list[str]:
        return imports(self.entries)


class Product:
    """What the screens read of the specs: the entities, their icons, the screens."""

    def __init__(self, specs: Specs):
        self.specs = specs
        self.entities = {it['id']: it for it in specs.product.get('entities', [])}
        self.icons = (specs.theme or {}).get('icons', {})
        self.screens = {key: value for key, value in specs.screens.items() if value is not None}
        self.roles = {it['id']: it for it in specs.product.get('roles', [])}

    def public(self, screen: dict) -> bool:
        """Whether an anonymous role uses the screen: it is routed outside the screens of a session."""
        return is_public(screen, self.roles)

    def generated(self) -> list[dict]:
        return [it for it in self.screens.values() if not it.get('custom')]

    def has_field(self, *types: str) -> bool:
        return any(field.get('type') in types for entity in self.entities.values() for field in entity['fields'])

    @property
    def packages(self) -> list[str]:
        return self.specs.product.get('packages', [])

    def host(self, card: dict) -> dict | None:
        """The list in whose layout a card is shown (`refs.host`)."""
        return host(card, self.screens)

    def parent(self, card: dict) -> dict | None:
        """The screen that a card links back to (`refs.parent`)."""
        return parent(card, self.screens, self.roles)


def route_to(product: Product, screen_id: str, item: str | None = None) -> Call:
    """`routeTo('<screen>')`, with the item of a screen of an item (`:id` in its route)."""
    args = [Str(screen_id)]
    if item is not None and ':' in product.screens[screen_id]['route']:
        args.append(Raw(item))
    return Call('routeTo', args)


def entity_constant(code: Code, consts: dict, entity_id: str) -> Raw:
    name = constant_name(entity_id)
    consts[name] = f'const {name} = ENTITIES.{entity_id};' if re.fullmatch(r'[A-Za-z_$][\w$]*', entity_id) else (
        f'const {name} = ENTITIES[{quote(entity_id)}];'
    )
    code.use('./entities', 'ENTITIES')
    return Raw(name)


class Form(NamedTuple):
    """The create form of an action: the action, the name of its state, its label and its entity."""

    action: dict
    state: Raw
    label: object
    entity: Raw


class Screen:
    """A screen being written: its code, its hooks and its constants."""

    def __init__(self, product: Product, data: dict):
        self.product, self.data = product, data
        self.code = Code()
        self.consts: dict[str, str] = {}
        #: the statements of the hooks of the component, by name
        self.hooks: dict[str, object] = {}
        #: the names that the code uses of `useLanguage()`
        self.language: set[str] = set()
        self.after: list = []
        #: whether the product extends the screen (`extend`): `extension` of src/screens/<id>/extend.tsx
        self.extended = bool(data.get('extend'))
        if self.extended:
            self.code.use(f'@/screens/{data["id"]}/extend', 'extension')

    def entity(self, entity_id: str) -> Raw:
        return entity_constant(self.code, self.consts, entity_id)

    def hook(self, name: str, statement, source: str, *names: str) -> None:
        self.hooks[name] = statement
        self.code.use(source, *names)

    def translate(self, *names: str) -> None:
        """`useLanguage()` with the names that the code uses of it: `t`, `language`."""
        self.language.update(names)
        self.hooks['t'] = f'const {{ {", ".join(sorted(self.language))} }} = useLanguage();'
        self.code.use('@/bazis/i18n', 'useLanguage')

    def route(self, screen_id: str, item: str | None = None) -> Call:
        """`routeTo(screen)`, the route of a screen (of an item: `item` is its id)."""
        self.code.use('./screens', 'routeTo')
        return route_to(self.product, screen_id, item)

    def go(self, target: Call) -> Void:
        """`void navigate(target)`, with the hook of the navigation."""
        self.hook('navigate', 'const navigate = useNavigate();', 'react-router', 'useNavigate')
        return Void(Call('navigate', [target]))

    def text(self, *path) -> Call | None:
        found = text(self.data, *path)
        if found is not None:
            self.translate('t')
        return found

    def package_text(self, key: str) -> Call:
        self.translate('t')
        return Call('t', [Str(key)])

    def create_forms(self) -> list[Form]:
        """
        The create forms of the actions (`CreateFormAction`), each of the entity of the screen or
        of its own (a dashboard), with their state; each written after the component.
        """
        forms = []
        for path, action in screen_actions(self.data):
            if action['primitive'] != 'form' or action.get('mode') != 'create':
                continue
            entity = self.entity(action.get('entity', self.data.get('entity')))
            state = self.form_state('CreateFormAction', action['id'])
            label = self.text(*path, 'label') or self.package_text('form.create')
            self.form_action('CreateFormAction', state, entity, action, label, self.text(*path, 'description'))
            forms.append(Form(action, state, label, entity))
        return forms

    def form_state(self, component: str, action_id: str) -> Raw:
        """The state of the form of an action, `<action>Form` (`CreateFormAction.use()`)."""
        state = camel(action_id) + 'Form'
        self.hook(state, f'const {state} = {component}.use();', '@/bazis/ui/screens', component)
        return Raw(state)

    def form_action(self, component: str, state: Raw, entity: Raw, action: dict, label, description=None) -> None:
        """
        The form of an action, written after the component: its fields, its title and its
        description, then the screen `then` of the action (that of the saved item for a screen
        of an item).
        """
        attrs = [Attr(SPREAD, state), Attr('path', Raw(f'{entity.code}.path'))]
        if component == 'UpdateFormAction':
            attrs.append(Attr('id', Raw('id')))
        if 'fields' in action:
            attrs.append(Attr('fields', Arr([Str(it) for it in action['fields']])))
        attrs.append(Attr('title', label))
        if description is not None:
            attrs.append(Attr('description', description))
        if 'then' in action:
            attrs.append(Attr('onSaved', self.on_saved(action['then'])))
        self.after.append(Jsx(component, attrs))

    def on_saved(self, screen_id: str) -> Arrow:
        """What a form does once it saved: it shows the screen, that of the saved item for a screen of an item."""
        target = self.route(screen_id, 'saved.data.id')
        return Arrow(['saved'] if len(target.args) > 1 else [], self.go(target))

    def write(self, body) -> str:
        """The module of the screen: its component, `<Id>Screen`, returning the body."""
        statements = list(self.hooks.values())
        component = Function(component_name(self.data['id']), '', Block([*statements, Return(body)]))
        return module(
            header(f'{SPEC_DIR}/screens/{self.data["id"]}.yaml'),
            *self.code.imports(),
            '\n'.join(self.consts.values()),
            printed(component.doc()),
        )


def component(screen: Screen, name: str, props: str, source: str, attrs: list[Attr], children=(), part='props') -> Jsx:
    """
    The component of a primitive with its attributes and children; of an extended screen, its
    props merged with those of the extension (`extended<Props>({...}, extension.props)`, the
    children a prop among them).
    """
    screen.code.use(source, name)
    if not screen.extended:
        return Jsx(name, attrs, list(children))
    screen.code.use(source, f'type {props}')
    screen.code.use('@/bazis/ui/screens', 'extended')
    # a prop of a name of its own is a shorthand: `id`
    entries = [
        (it.name, None if isinstance(it.value, Raw) and it.value.code == it.name else attr_value(it.value))
        for it in attrs
    ]
    if children:
        entries.append(('children', children[0] if len(children) == 1 else Jsx('', [], list(children))))
    merged = Call(f'extended<{props}>', [Obj(entries), Raw(f'extension.{part}')])
    return Jsx(name, [Attr(SPREAD, merged)])


def attr_value(value) -> Expr:
    """The value of an attribute as that of a prop: a string, `true`, or the expression."""
    if value is True:
        return Raw('true')
    return Str(value) if isinstance(value, str) else value


def extension_body(screen: Screen, body: list) -> list:
    """The body of a screen: of an extended one, between what the extension shows before and after it."""
    if not screen.extended:
        return body
    return [Raw('extension.before'), *body, Raw('extension.after')]


def extension_actions(screen: Screen, actions):
    """
    The actions of the header of a screen (None without any): of an extended one, those of
    the specs then those of the extension.
    """
    if not screen.extended:
        return actions
    parts = [] if actions is None else actions.children if actions.name == '' else [actions]
    return Jsx('', [], [*parts, Raw('extension.actions')]) if parts else Raw('extension.actions')


def screen_attrs(screen: Screen, parent: dict | None = None) -> list[Attr]:
    attrs = [Attr('id', screen.data['id'])]
    # a card heads the screen with the label of its item, its `h1`, instead of a title
    if screen.data['primitive'] != 'card' and (title := screen.text('title')) is not None:
        attrs.append(Attr('title', title))
    if parent is not None:
        if (label := text(parent, 'title')) is not None:
            screen.translate('t')
        attrs.append(Attr('parent', Obj([
            ('screen', Str(parent['id'])),
            ('label', label if label is not None else Str(parent['id'])),
            ('to', screen.route(parent['id'])),
        ])))
    if (description := screen.text('description')) is not None:
        attrs.append(Attr('description', description))
    return attrs


def filter_value(screen: Screen, where: dict) -> Call:
    """A filter of the specs: each field equal to its value (`Filter.and` of several)."""
    screen.code.use('@/bazis/client', 'Filter')
    parts = [Call('Filter.where', [Str(key), _scalar(value)]) for key, value in where.items()]
    return parts[0] if len(parts) == 1 else Call('Filter.and', parts)


def filter_expr(screen: Screen, where: dict) -> Raw:
    """The filter of a list (`list.filter`), a constant of the module."""
    screen.consts['FILTER'] = printed(Const('FILTER', filter_value(screen, where)).doc())
    return Raw('FILTER')


def _scalar(value) -> Str | Raw:
    if isinstance(value, bool):
        return Raw('true' if value else 'false')
    if isinstance(value, str):
        return Str(value)
    return Raw(repr(value))


def render_list(product: Product, data: dict) -> str:
    screen = Screen(product, data)
    spec = data['list']
    entity_id = data['entity']
    entity = product.entities[entity_id]
    const = screen.entity(entity_id)
    attrs = [Attr('path', Raw(f'{const.code}.path')), Attr('entity', entity_id)]
    attrs.append(Attr('columns', Arr([Str(it) for it in spec['columns']])))
    if 'filters' in spec:
        attrs.append(Attr('filters', Arr([list_filter(screen, entity, const, it) for it in spec['filters']])))
    if 'filter' in spec:
        attrs.append(Attr('filter', filter_expr(screen, spec['filter'])))
    if 'sort' in spec:
        attrs.append(Attr('sort', Arr([Str(it) for it in spec['sort']])))
    if spec.get('search'):
        attrs.append(Attr('search'))
    attrs += entity_attrs(product, entity_id, const, label=False)
    opened = []
    if any(it['primitive'] == 'card' and product.host(it) is data for it in product.screens.values()):
        screen.hook('id', 'const { id } = useParams();', 'react-router', 'useParams')
        opened.append(Attr('selected', Raw('id')))
    if 'open' in spec:
        opened.append(Attr('onOpen', Arrow(['item'], screen.go(screen.route(spec['open'], 'item')))))
    attrs += opened
    attrs += list_actions(screen, const)
    if 'bulk' in spec:
        attrs.append(Attr('bulk', Arr([bulk_action(screen, const, i, it) for i, it in enumerate(spec['bulk'])])))
    if 'highlight' in spec:
        attrs += highlight_attrs(screen, spec['highlight'])
    if (empty := screen.text('list', 'empty')) is not None:
        attrs.append(Attr('emptyMessage', empty))
    body = [component(screen, 'ResourceList', 'ResourceListProps', '@/bazis/ui/resource-list', attrs)]
    if 'map' in spec:
        body.insert(0, list_map(screen, const, spec, opened))
    return screen.write(screen_element(screen, body))


def list_actions(screen: Screen, const: Raw) -> list[Attr]:
    """
    The actions of the toolbar of a list in the order of the spec, its create forms and the
    custom actions of the route set, and those of the items in each row (`list.row_actions`).
    """
    creates = {it.action['id']: create_action(screen, it) for it in screen.create_forms()}
    rows = screen.data['list'].get('row_actions', [])
    toolbar, row_actions = [], {}
    for i, action in enumerate(screen.data.get('actions', [])):
        if action['id'] in creates:
            toolbar.append(creates[action['id']])
        elif action['primitive'] == 'custom':
            name = custom_action(screen, const, ('actions', i), action, 'item' if action['id'] in rows else 'route')
            if action['id'] in rows:
                row_actions[action['id']] = Raw(f'{name}.row')
            else:
                toolbar.append(Raw(f'{name}.action'))
    attrs = [Attr('actions', Arr(toolbar))] if toolbar else []
    if rows:
        attrs.append(Attr('rowActions', Arr([row_actions[it] for it in rows])))
    return attrs


def list_map(screen: Screen, const: Raw, spec: dict, opened: list[Attr]) -> Jsx:
    """
    The map of the items of a list beside it (`list.map`): those of the filter of the screen,
    the open one selected, a marker opening its card as a row does.
    """
    attrs = [Attr('path', Raw(f'{const.code}.path')), Attr('entity', screen.data['entity'])]
    attrs.append(Attr('field', spec['map']['field']))
    if 'filter' in spec:
        attrs.append(Attr('filter', Raw('FILTER')))
    return component(screen, 'ResourceMap', 'ResourceMapProps', '@/bazis/ui/map', attrs + opened, part='map')


def transitions(product: Product, entity_id: str) -> list[dict]:
    """The transitions of the workflow of the entity, in their order."""
    return product.entities[entity_id].get('workflow', {}).get('transitions', [])


def has_display(product: Product, entity_id: str) -> bool:
    """Whether the entity says how some of its values are shown (`display` of its fields)."""
    return any('display' in it for it in product.entities[entity_id]['fields'])


def entity_attrs(product: Product, entity_id: str, const: Raw, label: bool) -> list[Attr]:
    """The attributes a list, a card and a board take from the entity: its label, its display and its icon."""
    entity = product.entities[entity_id]
    attrs = []
    if label and 'label' in entity:
        attrs.append(Attr('label', Raw(f'{const.code}.label')))
    if has_display(product, entity_id):
        attrs.append(Attr('display', Raw(f'{const.code}.display')))
    if not label and entity_id in product.icons:
        attrs.append(Attr('icon', Raw(f'{const.code}.Icon')))
    return attrs


def list_filter(screen: Screen, entity: dict, const: Raw, name: str):
    """A filter of a list: the status one lists the statuses of the workflow."""
    if name != 'status' or 'workflow' not in entity:
        return Str(name)
    screen.translate('language')
    screen.code.use('@/bazis/ui/status-badge', 'statusOptions')
    options = Call('statusOptions', [Raw(f'{const.code}.type'), Raw('language')])
    return Obj([('field', Str('status')), ('options', options)])


def create_action(screen: Screen, form: Form) -> Obj:
    """The action of a list opening a create form."""
    screen.code.use('lucide-react', icon_name(CREATE_ICON))
    return Obj([
        ('id', Str(form.action['id'])), ('label', form.label), ('icon', Raw(icon_name(CREATE_ICON))),
        ('permission', Str('add')), ('onClick', Raw(f'{form.state.code}.onOpen')),
    ])


def highlight_attrs(screen: Screen, highlight: dict) -> list[Attr]:
    """The tone of the rows whose flag is set, and its label."""
    screen.code.use('@/bazis/ui/resource', 'fieldValue')
    test = Raw(f'fieldValue(row, {quote(highlight["field"])}) === true')
    attrs = [Attr('rowTone', Arrow(['row'], Cond(test, Str(highlight['tone']), Raw('undefined'))))]
    if (label := screen.text('list', 'highlight', 'label')) is not None:
        attrs.append(Attr('rowToneLabel', Arrow(['row'], Cond(test, label, Raw('undefined')))))
    return attrs


def custom_action(
    screen: Screen, const: Raw, path: tuple, action: dict, target: str, item: Raw | None = None, bulk: bool = False,
) -> str:
    """
    A custom action (`useCustomAction`) at the path of its spec, `<id>Action`, of the items
    (`target` item) or of the route set (`route`, the toolbar of a list), of the item of a card
    (`item`), its dialog (with the labels of its fields) written after the screen; of a bulk action, `<id>Bulk`, without a
    dialog (it asks for nothing).
    """
    name = camel(action['id']) + ('Bulk' if bulk else 'Action')
    options = [
        ('id', Str(action['id'])), ('label', screen.text(*path, 'label')),
        ('path', Raw(f'{const.code}.path')), ('action', Str(action['action'])), ('target', Str(target)),
    ]
    if item is not None:
        options.append(('item', item))
    if 'fields' in action:
        options.append(('fields', Arr([Str(it) for it in action['fields']])))
    if 'labels' in action:
        options.append(('labels', Obj([(name, screen.text(*path, 'labels', name)) for name in action['labels']])))
    for key in ('title', 'description'):
        if (value := screen.text(*path, key)) is not None:
            options.append((key, value))
    if 'confirm' in action:
        options.append(('confirm', Raw('true' if action['confirm'] else 'false')))
    if (message := screen.text(*path, 'message')) is not None:
        options.append(('message', message))
    screen.hook(name, Const(name, Call('useCustomAction', [Obj(options)])), '@/bazis/ui/screens', 'useCustomAction')
    if not bulk:
        screen.after.append(Raw(f'{name}.dialog'))
    return name


def bulk_action(screen: Screen, const: Raw, index: int, bulk: dict) -> Obj | Raw:
    if 'action' in bulk:
        # a custom action of the items, without a dialog: `<id>Bulk`
        return Raw(custom_action(screen, const, ('list', 'bulk', index), bulk, 'item', bulk=True) + '.bulk')
    props = [('id', Str(bulk['id']))]
    label = screen.text('list', 'bulk', index, 'label')
    if 'transit' in bulk:
        statement = f'const transit = useItemsTransit({const.code}.path);'
        screen.hook('transit', statement, '@/bazis/react/statusy', 'useItemsTransit')
        if label is None:
            screen.translate('language')
            screen.code.use('@/bazis/ui/status-badge', 'transitName')
            label = Call('transitName', [Raw(f'{const.code}.type'), Str(bulk['transit']), Raw('language')])
        run = Call('transit.mutateAsync', [Obj([('id', Raw('item')), ('transit', Str(bulk['transit']))])])
        props += [('label', label), ('run', Arrow(['item'], run))]
    else:
        screen.hook('destroy', f'const destroy = useDestroy({const.code}.path);', '@/bazis/react', 'useDestroy')
        props += [
            ('label', label or screen.package_text('card.delete')),
            ('permission', Str('delete')),
            ('variant', Str('destructive')),
            ('run', Arrow(['item'], Call('destroy.mutateAsync', [Raw('item')]))),
        ]
    return Obj(props)


def render_card(product: Product, data: dict) -> str:
    screen = Screen(product, data)
    spec = data['card']
    entity_id = data['entity']
    const = screen.entity(entity_id)
    screen.hook('id', "const { id = '' } = useParams();", 'react-router', 'useParams')
    attrs = [Attr('path', Raw(f'{const.code}.path')), Attr('id', Raw('id'))]
    attrs.append(Attr('sections', Arr([card_section(screen, i, it) for i, it in enumerate(spec['sections'])])))
    attrs += entity_attrs(product, entity_id, const, label=True)
    if spec.get('edit'):
        attrs.append(Attr('edit'))
    if 'workflow' in product.entities[entity_id]:
        screen.code.use('@/bazis/ui/status-badge', 'StatusBadge')
        attrs.append(Attr('badge', Arrow(['item'], Jsx('StatusBadge', [Attr('resource', Raw('item'))]))))

    related = {it['id']: related_list(screen, i, it) for i, it in enumerate(spec.get('related', []))}
    history = Jsx('StatusHistory', [Attr('resource', Raw('item'))]) if spec.get('history') else None
    if history is not None:
        screen.code.use('@/bazis/ui/status-history', 'StatusHistory')
    children = [transit_bar(screen, const)] if spec.get('transitions') else []
    if 'tabs' in spec:
        tabs = [card_tab(screen, i, it, related, history) for i, it in enumerate(spec['tabs'])]
        attrs.append(Attr('tabs', Arr(tabs)))
        render_props = []
    else:
        render_props = [*related.values(), *([history] if history is not None else [])]
    card_actions = []
    for i, action in enumerate(data.get('actions', [])):
        if action['primitive'] == 'destroy':
            card_actions.append(destroy_action(screen, const, i, action))
        elif action.get('mode') == 'update':
            card_actions.append(update_action(screen, const, i, action))
        elif action['primitive'] == 'custom':
            card_actions.append(Raw(custom_action(screen, const, ('actions', i), action, 'item', Raw('id')) + '.action'))
    if card_actions:
        attrs.append(Attr('actions', Arr(card_actions)))
    header = header_actions(screen)

    if render_props:
        body = Jsx('', [], render_props) if len(render_props) > 1 else render_props[0]
        attrs.append(Attr('after', render_prop(render_props, body)))
    card = component(screen, 'ResourceCard', 'ResourceCardProps', '@/bazis/ui/resource-card', attrs, children)
    return screen.write(screen_element(screen, [card], header, product.parent(data)))


def screen_element(screen: Screen, body: list, actions=None, parent: dict | None = None) -> Jsx:
    """`Screen` with its title, its parent, its description and the actions of its header, then the body and what follows it."""
    screen.code.use('@/bazis/ui/app-shell', 'Screen')
    attrs = screen_attrs(screen, parent)
    if (actions := extension_actions(screen, actions)) is not None:
        attrs.append(Attr('actions', actions))
    return Jsx('Screen', attrs, [*extension_body(screen, body), *screen.after])


def card_section(screen: Screen, index: int, section: dict) -> Obj:
    props = [('id', Str(section['id']))]
    if (title := screen.text('card', 'sections', index, 'title')) is not None:
        props.append(('title', title))
    props.append(('fields', Arr([Str(it) for it in section['fields']])))
    return Obj(props)


def card_tab(screen: Screen, index: int, tab: dict, related: dict, history) -> Obj:
    props = [('id', Str(tab['id'])), ('title', screen.text('card', 'tabs', index, 'title'))]
    if 'sections' in tab:
        props.append(('sections', Arr([Str(it) for it in tab['sections']])))
    parts = [related[it] for it in tab.get('related', [])] + ([history] if tab.get('history') else [])
    if parts:
        props.append(('content', content(parts)))
    return Obj(props)


def transit_bar(screen: Screen, const: Raw) -> Jsx:
    """
    The transitions of the card, in the order of the workflow; once the user can no longer
    view the item, its list is opened.
    """
    screen.code.use('@/bazis/ui/transit-bar', 'TransitBar')
    attrs = [Attr('path', Raw(f'{const.code}.path')), Attr('id', Raw('id'))]
    if transitions(screen.product, screen.data['entity']):
        attrs.append(Attr('transits', Raw(f'{const.code}.transits')))
    parent = screen.product.parent(screen.data)
    if parent is not None:
        back = If(Raw('done === null'), screen.go(screen.route(parent['id'])))
        attrs.append(Attr('onDone', Arrow(['done'], Block([back]))))
    return Jsx('TransitBar', attrs)


def destroy_action(screen: Screen, const: Raw, index: int, action: dict) -> Raw:
    """The delete action of a card (`useDestroyCardAction`); its confirmation is written after the card."""
    name = camel(action['id']) + 'Action'
    label = screen.text('actions', index, 'label') or screen.package_text('card.delete')
    options = [('id', Str(action['id'])), ('label', label)]
    if (title := screen.text('actions', index, 'title')) is not None:
        options.append(('title', title))
    if (description := screen.text('actions', index, 'description')) is not None:
        options.append(('description', description))
    options += [('path', Raw(f'{const.code}.path')), ('item', Raw('id'))]
    if 'then' in action:
        options.append(('then', screen.route(action['then'])))
    hook = Const(name, Call('useDestroyCardAction', [Obj(options)]))
    screen.hook(name, hook, '@/bazis/ui/screens', 'useDestroyCardAction')
    screen.after.append(Raw(f'{name}.confirm'))
    return Raw(f'{name}.action')


def update_action(screen: Screen, const: Raw, index: int, action: dict) -> Obj:
    """The update form of the item of a card (`UpdateFormAction`), opened by an action of the card that the user may change."""
    state = screen.form_state('UpdateFormAction', action['id'])
    label = screen.text('actions', index, 'label') or screen.package_text('card.edit')
    screen.form_action('UpdateFormAction', state, const, action, label, screen.text('actions', index, 'description'))
    return Obj([
        ('id', Str(action['id'])), ('label', label), ('permission', Str('change')),
        ('onClick', Raw(f'{state.code}.onOpen')),
    ])


def header_actions(screen: Screen) -> Jsx | None:
    """
    The create forms of the actions of a screen opened from its header (`ScreenAction`), each
    shown once the user may add an item of its entity; None without them.
    """
    forms = screen.create_forms()
    if not forms:
        return None
    screen.code.use('@/bazis/ui/screens', 'ScreenAction')
    screen.code.use('lucide-react', icon_name(CREATE_ICON))
    buttons = [
        Jsx('ScreenAction', [
            Attr('id', it.action['id']), Attr('label', it.label), Attr('icon', Raw(icon_name(CREATE_ICON))),
            Attr('requires', Obj([('path', Raw(f'{it.entity.code}.path')), ('can', Str('add'))])),
            Attr('onClick', Raw(f'{it.state.code}.onOpen')),
        ])
        for it in forms
    ]
    return buttons[0] if len(buttons) == 1 else Jsx('', [], buttons)


def needs_meta(parts: list) -> bool:
    return any(isinstance(it, _Related) and it.gated for it in parts)


def content(parts: list) -> Arrow:
    """The content of a tab: its related sections and its history."""
    return render_prop(parts, parts[0] if len(parts) == 1 else Jsx('', [], parts))


def render_prop(parts: list, body) -> Arrow:
    """
    A function of the item of a card and of its permission meta rendering the parts of the card
    (the body): the parameters that they use, the item for the history, the meta for an "add
    here" shown while the user may change the item.
    """
    meta = needs_meta(parts)
    item = any(isinstance(it, Jsx) and it.name == 'StatusHistory' for it in parts)
    params = ['item' if item else '_', 'meta'] if meta else ['item'] if item else []
    return Arrow(params, body)


class _Related(Jsx):
    """A related section, whose "add here" is shown while the user may change the item (`gated`)."""

    gated: bool = False


def related_list(screen: Screen, index: int, related: dict) -> Jsx:
    target = screen.entity(related['entity'])
    owner = Raw(f'{constant_name(screen.data["entity"])}.path')
    attrs = [
        Attr('path', Raw(f'{target.code}.path')), Attr('entity', related['entity']),
        Attr('relation', related['relation']), Attr('item', Raw('id')), Attr('itemPath', owner),
    ]
    if (title := screen.text('card', 'related', index, 'title')) is not None:
        attrs.append(Attr('title', title))
    attrs.append(Attr('columns', Arr([Str(it) for it in related['columns']])))
    attrs += entity_attrs(screen.product, related['entity'], target, label=False)
    if 'open' in related:
        attrs.append(Attr('onOpen', Arrow(['item'], screen.go(screen.route(related['open'], 'item')))))
    element = _Related('RelatedList', attrs)
    if 'add' in related:
        add = related['add']
        props = [
            ('id', Str(add['id'])),
            ('label', screen.text('card', 'related', index, 'add', 'label') or screen.package_text('form.create')),
        ]
        if 'fields' in add:
            props.append(('fields', Arr([Str(it) for it in add['fields']])))
        if add.get('when', 'changeable') == 'changeable':
            screen.code.use('@/bazis/ui/resource', 'permitted')
            attrs.append(Attr('add', Cond(Raw("permitted(meta, 'change')"), Obj(props), Raw('undefined'))))
            element.gated = True
        else:
            attrs.append(Attr('add', Obj(props)))
    screen.code.use('@/bazis/ui/resource-card', 'RelatedList')
    return element


def render_dashboard(product: Product, data: dict) -> str:
    """
    A dashboard: the create forms of its actions in its header, its tiles, its charts and its
    last items, each of its own entity (`Dashboard` is the screen: its forms are its children).
    """
    screen = Screen(product, data)
    spec = data['dashboard']
    attrs = screen_attrs(screen)
    if (actions := extension_actions(screen, header_actions(screen))) is not None:
        attrs.append(Attr('actions', actions))
    parts = []
    if spec.get('tiles'):
        parts.append(Attr('tiles', Arr([tile(screen, i, it) for i, it in enumerate(spec['tiles'])])))
    if spec.get('charts'):
        charts = [chart(screen, i, it) for i, it in enumerate(spec['charts'])]
        parts.append(Attr('charts', charts[0] if len(charts) == 1 else Jsx('', [], charts)))
    if spec.get('recent'):
        parts.append(Attr('recent', Arr([recent_list(screen, i, it) for i, it in enumerate(spec['recent'])])))
    # the dashboard is the screen: the extension gives it what it shows before its parts and
    # after them, the props of its parts merged
    if screen.extended:
        attrs.append(Attr('before', Raw('extension.before')))
        dashboard = component(screen, 'Dashboard', 'DashboardProps', '@/bazis/ui/dashboard', parts)
        return screen.write(Jsx('Dashboard', [*attrs, *dashboard.attrs], [Raw('extension.after'), *screen.after]))
    screen.code.use('@/bazis/ui/dashboard', 'Dashboard')
    return screen.write(Jsx('Dashboard', [*attrs, *parts], screen.after))


def tile(screen: Screen, index: int, spec: dict) -> Obj:
    """
    A tile counting the items of its filter, or showing an aggregate of a field of them (shown
    as the display of the entity says), with its icon (that of its entity), opening its list.
    """
    const = screen.entity(spec['entity'])
    props = [('id', Str(spec['id'])), ('path', Raw(f'{const.code}.path'))]
    if 'filter' in spec:
        props.append(('filter', filter_value(screen, spec['filter'])))
    if 'value' in spec:
        props.append(('value', aggregate_value(spec['value'])))
        if has_display(screen.product, spec['entity']):
            props.append(('display', Raw(f'{const.code}.display')))
    props.append(('label', screen.text('dashboard', 'tiles', index, 'label')))
    if 'tone' in spec:
        props.append(('tone', Str(spec['tone'])))
    if 'icon' in spec:
        screen.code.use('lucide-react', icon_name(spec['icon']))
        props.append(('icon', Raw(icon_name(spec['icon']))))
    elif spec['entity'] in screen.product.icons:
        props.append(('icon', Raw(f'{const.code}.Icon')))
    if 'open' in spec:
        props.append(('onOpen', Arrow([], screen.go(screen.route(spec['open'])))))
    props += part_requires(spec)
    return Obj(props)


def part_requires(spec: dict) -> list[tuple[str, Obj]]:
    """The `requires` of a tile or the last items when the user must be allowed to add an item (view is the default)."""
    return [('requires', Obj([('can', Str('add'))]))] if adds(spec) else []


def adds(spec: dict) -> bool:
    return spec.get('requires', {}).get('can') == 'add'


def chart(screen: Screen, index: int, spec: dict) -> Jsx:
    """
    A chart of the items of an entity by its status (`StatusChart`) or by a date (`TimeChart`),
    shown to the users who may view them, and add one with `requires` (`Viewable`, as the tiles
    and the last items).
    """
    const = screen.entity(spec['entity'])
    attrs = [Attr('id', spec['id']), Attr('path', Raw(f'{const.code}.path'))]
    by_status = spec['by'] == 'status' and 'workflow' in screen.product.entities[spec['entity']]
    if not by_status:
        attrs.append(Attr('field', spec['by']))
    attrs += [Attr('label', screen.text('dashboard', 'charts', index, 'label')), Attr('kind', spec['kind'])]
    if 'bucket' in spec:
        attrs.append(Attr('bucket', spec['bucket']))
    if 'last' in spec:
        attrs.append(Attr('last', Raw(str(spec['last']))))
    if 'value' in spec:
        attrs.append(Attr('value', aggregate_value(spec['value'])))
    name = 'StatusChart' if by_status else 'TimeChart'
    screen.code.use('@/bazis/ui/charts', name)
    screen.code.use('@/bazis/ui/dashboard', 'Viewable')
    viewable = [Attr('path', Raw(f'{const.code}.path'))]
    if adds(spec):
        viewable.append(Attr('can', 'add'))
    return Jsx('Viewable', viewable, [Jsx(name, attrs)])


def aggregate_value(value: dict) -> Obj:
    """The `value` of a tile or a chart as its prop: `{ sum: 'amount' }`."""
    return Obj([(func, Str(name)) for func, name in value.items()])


