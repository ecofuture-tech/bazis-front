def render(specs: Specs) -> dict[str, str]:
    """
    The generated files by their path in the frontend, from specs without errors.
    """
    product = Product(specs)
    files = {
        ENTITIES_TS: render_entities(product),
        SCREENS_TS: render_screens(product),
        ROUTES_TSX: render_routes(product),
        NAVIGATION_TS: render_navigation(product),
        MESSAGES_TS: render_messages(product, texts(specs)),
        PRODUCT_TS: render_product(product),
        PROVIDERS_TSX: render_providers(product),
        TOOLS_TSX: render_tools(product),
    }
    for data in product.generated():
        files[f'{GENERATED_DIR}/{data["id"]}.tsx'] = RENDERERS[data['primitive']](product, data)
    return dict(sorted(files.items()))


#: a module of the copies that a generated file imports
COPY = re.compile(r"from '@/(bazis/[^']+)'")


def assets(rendered: dict[str, str]) -> list[str]:
    """The assets whose modules the generated files import, by name."""
    targets = {it.target: it.name for it in load_registry().values()}
    modules = {f'src/{it}' for text in rendered.values() for it in COPY.findall(text)}
    return sorted(targets[it] for it in modules if it in targets)


#: what `front.W010` and `bazis_front update` say of a frontend that `needs_screens`
NEEDS_SCREENS = 'The template needs the generated screens: run `manage.py bazis_front screens`.'


def missing_assets(lock: dict, rendered: dict[str, str]) -> list[str]:
    """The assets that the generated files import and the frontend lacks."""
    return [it for it in assets(rendered) if it not in lock.get('assets', {})]


def spec_hashes(root: Path) -> dict[str, str]:
    """
    The hashes of the specs that the screens are generated from, by their path in the
    product root: product.yaml, the screens and theme.yaml (the icons).
    """
    return frontend_lock.file_hashes(root, [PRODUCT_FILE, *screen_files(root), THEME_FILE])


def generated_path(frontend: Path, path: str) -> bool:
    """
    Whether a path of the lock is a file of `src/screens/generated/` of the frontend: the
    generator never deletes, reports or overwrites any other, whatever the lock lists.
    """
    return (frontend / path).resolve().is_relative_to((frontend / GENERATED_DIR).resolve())


def removed_files(frontend: Path, lock: dict, rendered: dict[str, str]) -> list[str]:
    """The generated files of the lock that the specs no longer generate and that still exist."""
    return sorted(
        path for path in lock.get('screens', {}).get('generated', {})
        if path not in rendered and generated_path(frontend, path) and (frontend / path).is_file()
    )


def edited_files(frontend: Path, lock: dict, rendered: dict[str, str]) -> list[str]:
    """
    The generated files edited since they were generated (their hash is not that of the
    lock) that the generation would change or delete: never overwritten without `--force`.
    """
    recorded = lock.get('screens', {}).get('generated', {})
    return sorted(
        path for path, digest in recorded.items()
        if generated_path(frontend, path) and (target := frontend / path).is_file()
        and frontend_lock.digest(target.read_bytes()) != digest
        and target.read_bytes() != rendered.get(path, '').encode('utf-8')
    )


def stale(root: Path, frontend: Path, lock: dict, rendered: dict[str, str]) -> list[str]:
    """
    Why the generated screens of the frontend differ from those of the specs, one message
    for each; empty when they are current. The files are compared byte for byte; those of
    the lock that the specs no longer generate are stale while they exist; the components
    that they import must be in the frontend.
    """
    names = frontend_lock.stale_files(frontend, rendered)
    removed = removed_files(frontend, lock, rendered)
    problems = []
    if names or removed:
        problems.append(
            f'The generated screens of {frontend} are stale: '
            + ', '.join([*names, *(f'{it} (of a screen that is no longer generated)' for it in removed)])
            + '.'
        )
        changed, _ = frontend_lock.generation_changes(lock.get('screens', {}), spec_hashes(root), frontend, names)
        if changed:
            problems.append(f'The specs changed since they were generated: {", ".join(changed)}.')
        if edited := edited_files(frontend, lock, rendered):
            problems.append(f'Edited after they were generated: {", ".join(edited)}.')
    if missing := missing_assets(lock, rendered):
        problems.append(f'The components that they import are not in the frontend: {", ".join(missing)}.')
    return problems


def write(root: Path, frontend: Path, lock: dict, rendered: dict[str, str]) -> list[str]:
    """
    Writes the generated screens, deletes those of the lock that the specs no longer
    generate and records the hashes of the specs and of the files in the lock. Returns the
    deleted paths.
    """
    removed = removed_files(frontend, lock, rendered)
    frontend_lock.write_files(frontend, rendered)
    for path in removed:
        (frontend / path).unlink()
    lock['screens'] = frontend_lock.generation(spec_hashes(root), rendered)
    frontend_lock.write(frontend, lock)
    return removed
