from bazis.contrib.front.vendor.lock import digest


REPOSITORY = Path(__file__).resolve().parent.parent
SAMPLE_SPEC = REPOSITORY / 'sample' / 'spec'
FIXTURES = REPOSITORY / 'bazis' / 'contrib' / 'front' / 'assets' / 'playwright' / 'generated'

MANAGER = 'e2e/generated/manager-finishes-a-task.spec.ts'
VIEWER = 'e2e/generated/viewer-only-reads.spec.ts'
EMPTY_TITLE = 'e2e/generated/manager-cannot-save-an-empty-title.spec.ts'
ASSIGNS = 'e2e/generated/manager-assigns-a-task.spec.ts'
ATTACHES = 'e2e/generated/manager-attaches-a-brief.spec.ts'
REPORT = 'e2e/generated/manager-cannot-change-the-report.spec.ts'
NOTIFIED = 'e2e/generated/manager-is-notified-of-a-finished-task.spec.ts'


@pytest.fixture
def root(tmp_path):
    """
    A product root with the specs of the sample and a frontend made by `init`.
    """
    shutil.copytree(SAMPLE_SPEC, tmp_path / 'spec')
    with override_settings(BASE_DIR=str(tmp_path)):
        call_command('bazis_front', 'init', '--no-node', stdout=StringIO())
        yield tmp_path


def generate(*args) -> str:
    out = StringIO()
    call_command('bazis_front', 'e2e', *args, stdout=out, stderr=StringIO())
    return out.getvalue()


def lock_of(root: Path) -> dict:
    return json.loads((root / 'frontend' / 'bazis-front.lock.json').read_text(encoding='utf-8'))


def edit_product(root: Path, change) -> None:
    path = root / 'spec' / 'product.yaml'
    data = yaml.safe_load(path.read_text(encoding='utf-8'))
    change(data)
    path.write_text(yaml.safe_dump(data, sort_keys=False), encoding='utf-8')


def rendered(root: Path) -> dict[str, str]:
    result = validate(root)
    assert not result.errors, [it.as_dict() for it in result.errors]
    return e2e.render(result.specs)


def test_the_tests_of_the_sample_are_the_fixture_of_the_helpers():
    files = {path.removeprefix('e2e/generated/'): text for path, text in rendered(REPOSITORY / 'sample').items()}
    if os.environ.get('BAZIS_FRONT_WRITE_FIXTURES') == '1':
        shutil.rmtree(FIXTURES, ignore_errors=True)
        FIXTURES.mkdir()
        for name, text in files.items():
            (FIXTURES / name).write_text(text, encoding='utf-8', newline='\n')
    assert sorted(files) == sorted(it.name for it in FIXTURES.iterdir())
    for name, text in files.items():
        assert (FIXTURES / name).read_text(encoding='utf-8') == text, name


def test_the_text_of_a_scenario():
    text = rendered(REPOSITORY / 'sample')[MANAGER]
    assert text.startswith(
        '// Generated by `manage.py bazis_front e2e` from the scenario `manager-finishes-a-task` '
        'of spec/product.yaml:\n// never edit it, change the specs and generate it again.\n\n'
        "import { test } from '@playwright/test';\n\n"
        "import { loginAs } from '../bazis';\n\n"
        "import { PRODUCT } from './product';\n\n"
        "test('manager-finishes-a-task', async ({ page }) => {\n"
        "  const app = await loginAs(page, PRODUCT, 'manager');\n"
    )
    # a step of the scenario is a step of the test, its title the step in YAML
    assert (
        "  await test.step('fill: {title: Write the report}', async () => {\n"
        "    await app.fill({ title: 'Write the report' });\n"
        '  });\n'
    ) in text
    # the form of `create` leads to its `then`, the card
    assert (
        "  await test.step('submit', async () => {\n"
        '    await app.submit();\n'
        "    await app.expectScreen('task-card');\n"
        '  });\n'
    ) in text
    assert "    await app.transit('finish', { report: 'Done' });\n" in text
    assert text.endswith(
        "    await app.expectStatus('done');\n"
        "    await app.expectFieldReadonly('title');\n"
        '  });\n'
        '});\n'
    )


