def test_the_steps_follow_the_walk_of_the_scenario(tmp_path):
    shutil.copytree(SAMPLE_SPEC, tmp_path / 'spec')

    def scenario(data):
        data['scenarios'].append({
            'id': 'manager-renames-a-task',
            'role': 'manager',
            'steps': [
                {'open': 'task-list'},
                {'expect': {'rows': 1, 'state': 'loaded'}},
                {'open_item': {'where': {'title': 'It\'s "the" report \\ 1'}}},
                # the edit of the card starts with its first change
                {'fill': {'title': 'Renamed'}},
                {'fill': {'report': ''}},
                {'submit': {}},
                {'expect': {'error': 'title'}},
                {'action': 'delete'},
            ],
        })

    edit_product(tmp_path, scenario)
    text = rendered(tmp_path)['e2e/generated/manager-renames-a-task.spec.ts']
    body = text[text.index('  await test.step'):]
    assert body == (
        "  await test.step('open: task-list', async () => {\n"
        "    await app.open('task-list');\n"
        '  });\n'
        "  await test.step('expect: {rows: 1, state: loaded}', async () => {\n"
        "    await app.expectState('loaded');\n"
        '    await app.expectRows(1);\n'
        '  });\n'
        """  await test.step('open_item: {where: {title: It\\'s "the" report \\\\ 1}}', async () => {\n"""
        """    await app.openItem({ where: { title: 'It\\'s "the" report \\\\ 1' } });\n"""
        "    await app.expectScreen('task-card');\n"
        '  });\n'
        "  await test.step('fill: {title: Renamed}', async () => {\n"
        "    await app.action('edit');\n"
        "    await app.fill({ title: 'Renamed' });\n"
        '  });\n'
        "  await test.step('fill: {report: \\'\\'}', async () => {\n"
        "    await app.fill({ report: '' });\n"
        '  });\n'
        "  await test.step('submit', async () => {\n"
        '    await app.submit();\n'
        '  });\n'
        "  await test.step('expect: {error: title}', async () => {\n"
        "    await app.expectError('title');\n"
        '  });\n'
        # a destroy leads to its `then`
        "  await test.step('action: delete', async () => {\n"
        "    await app.action('delete');\n"
        "    await app.expectScreen('task-list');\n"
        '  });\n'
        '});\n'
    )


def test_a_submit_followed_by_an_error_fails():
    result = validate(REPOSITORY / 'sample')
    steps = [(it.name, it.edit, it.then) for it in result.specs.scenarios['manager-cannot-save-an-empty-title']]
    assert steps == [
        ('open', False, None),
        ('action', False, None),
        ('fill', False, None),
        # the next step expects an error: the form of `create` stays open, no `then`
        ('submit', False, None),
        ('expect', False, None),
        ('fill', False, None),
        ('submit', False, 'task-card'),
        ('expect', False, None),
        # the edit of the card starts with its first change
        ('fill', True, None),
        ('submit', False, None),
        ('expect', False, None),
        # the edit is still open after the failing submit
        ('fill', False, None),
        ('submit', False, None),
        ('transit', False, None),
        ('expect', False, None),
    ]
    text = rendered(REPOSITORY / 'sample')[EMPTY_TITLE]
    assert text.count("await app.action('edit');") == 1
    assert text.count("await app.expectScreen('task-card');") == 2


