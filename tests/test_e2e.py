"""
The end-to-end tests generated from the scenarios (`bazis_front e2e`): the text of those of
the sample is the fixture of the helpers (`assets/playwright/generated/`, type-checked
against them; with `BAZIS_FRONT_WRITE_FIXTURES=1` the test writes it), the files and the
lock in a frontend, the deletion of the tests of a removed scenario, `--check` and
`front.W003`.
"""

