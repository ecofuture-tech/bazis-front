import json
from io import StringIO

from django.core.checks import Warning, register
from django.core.checks.registry import registry
from django.core.management import call_command
from django.test import override_settings

import pytest

from bazis.contrib.front import __version__, checks
from bazis.contrib.front.management.commands.bazis_front import Command


@pytest.fixture
def product(tmp_path):
    with override_settings(BASE_DIR=str(tmp_path)):
        yield tmp_path


def status(*args):
    out = StringIO()
    call_command('bazis_front', 'status', *args, stdout=out)
    return out.getvalue()


def test_the_status_of_a_product_without_a_frontend(product):
    assert json.loads(status('--json')) == {
        'bazis_front': __version__,
        'frontend': None,
        'assets': {},
        'generated': {'contract': False, 'design': False, 'e2e': False},
        'issues': [],
    }
    text = status()
    assert 'no frontend made by `bazis_front init`' in text
    assert text.endswith('No issues.\n')


@pytest.mark.django_db
def test_the_status_of_a_frontend(sample_app, product):
    call_command('bazis_front', 'init', '--no-node', stdout=StringIO(), stderr=StringIO())
    state = json.loads(status('--json'))
    assert state['frontend'] == str(product / 'frontend')
    assert state['assets']['client'] == __version__
    assert state['assets']['template'] == __version__
    # the theme is generated by init, the contract and the end-to-end tests are not
    assert state['generated'] == {'contract': False, 'design': True, 'e2e': False}
    assert [it['id'] for it in state['issues']] == ['front.W001']
    assert state['issues'][0]['level'] == 'warning'
    # the subcommand that brings it up to date
    assert state['issues'][0]['command'] == 'contract'

    call_command('bazis_front', 'contract', '--no-node', stdout=StringIO(), stderr=StringIO())
    client = product / 'frontend' / 'src' / 'bazis' / 'client' / 'client.ts'
    client.write_text(client.read_text(encoding='utf-8') + '// changed\n', encoding='utf-8')
    state = json.loads(status('--json'))
    assert state['generated']['contract'] is True
    # the generated schema.d.ts is missing without Node (front.W001), the client was changed
    assert [(it['id'], it['command']) for it in state['issues']] == [
        ('front.W001', 'contract'),
        ('front.W007', None),
    ]
    text = status()
    assert f'{product / "frontend"}: ' in text
    assert 'Generated: contract, design; not generated: e2e.' in text
    assert 'front.W007 warning: ' in text
    assert text.endswith('2 issues.\n')


def test_the_subcommands_run_no_system_checks(product, capsys):
    # a warning of another package, printed by the system checks before a command
    def noisy(app_configs, **kwargs):
        return [Warning('noise', id='other.W001')]

    register(noisy)
    try:
        Command().run_from_argv(['manage.py', 'bazis_front', 'status', '--json'])
    finally:
        registry.registered_checks.discard(noisy)
    out, err = capsys.readouterr()
    assert json.loads(out)['issues'] == []
    assert 'other.W001' not in out + err


def test_the_status_runs_every_check_of_bazis_front():
    registered = {it for it in registry.get_checks() if it.__module__ == checks.__name__}
    assert set(checks.STATUS) == registered
    assert len(checks.STATUS) == len(registered)
